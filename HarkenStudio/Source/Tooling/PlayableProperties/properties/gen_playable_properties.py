"""Generate PlayablePropertyRegistryV1 products from its sole JSON authority."""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "harken_playable_property_table.json")
CONTRACT_OUT = os.path.normpath(os.path.join(HERE, "..", "generated"))
RUNTIME_OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "..", "..", "..", "HarkenEngine", "Source", "Runtime", "core", "include", "harken", "core",
    "generated"))
PACK_BUILD_OUT = os.path.normpath(os.path.join(
    HERE, "..", "..", "PackBuild", "include", "harken_studio_build"))
REGEN = ("py -3 HarkenStudio/Source/Tooling/PlayableProperties/properties/"
         "gen_playable_properties.py")

WIRES = ["f32", "u8", "u32", "objectid", "rowSpan", "effectProgram"]
COMBINES = ["dbSum", "centSumClamp", "objectLocal",
            "leafMaterialization", "nearestExplicit", "sendResolution",
            "effectSelection"]
REFERENCES = ["none", "mainOutputBus", "attenuation"]
CAPABILITIES = ["common", "playback", "streaming", "route", "send",
                "spatial", "reserved", "effect"]
PHASES = ["firstAudible", "playbackMaterialization", "leafMaterialization",
          "route", "sameCutInstall"]
DEFAULTS = ["+0.0f", "1.0f", "0", "empty", "1"]
COMPONENTS = ["mixnode", "audio", "spatial"]


class TableError(Exception):
    pass


def enum_name(value):
    special = {"+0.0f": "PositiveZero", "1.0f": "One",
               "0": "Zero", "empty": "Empty", "1": "IntegerOne",
               "objectid": "ObjectId"}
    if value in special:
        return special[value]
    return value[0].upper() + value[1:]


def load_table():
    with open(SOURCE, "r", encoding="utf-8") as handle:
        table = json.load(handle)
    if table.get("vintage") != 1 or table.get("knownMask") != "0x000000000001afff":
        raise TableError("V1 keeps the authored property ids with ids 13 and 15 retired")
    kinds = table.get("contentKinds")
    fields = table.get("fields")
    if not isinstance(kinds, list) or not isinstance(fields, list):
        raise TableError("contentKinds and fields must be lists")
    if [(row.get("ordinal"), row.get("name")) for row in kinds] != [
            (0, "Layer"), (1, "Sound"), (2, "Container"),
            (3, "Track"), (4, "Segment")]:
        raise TableError("ContentPropertyKindV1 must be Layer0..Segment4")
    if [row.get("id") for row in fields] != list(range(1, 13)) + [14, 16, 17]:
        raise TableError("property ids must be 1..12, 14, 16 and 17; ids 13 and 15 are retired")
    names = [row.get("name") for row in fields]
    keys = [row.get("jsonKey") for row in fields]
    storage = [(row.get("component"), row.get("storageField")) for row in fields]
    if len(set(names)) != 15 or len(set(keys)) != 15 or len(set(storage)) != 15:
        raise TableError("property names, JSON keys, and Studio storage must be unique")
    for row in fields:
        if row.get("present") != "maskBit":
            raise TableError("every V1 property uses an exact presence mask bit")
        checks = (("wire", WIRES), ("combineRole", COMBINES),
                  ("referenceRole", REFERENCES),
                  ("capabilityRole", CAPABILITIES),
                  ("phaseRole", PHASES),
                  ("canonicalDefault", DEFAULTS))
        for key, allowed in checks:
            if row.get(key) not in allowed:
                raise TableError("field %d has invalid %s" % (row["id"], key))
        if row.get("component") not in COMPONENTS:
            raise TableError("field %d has invalid component" % row["id"])
        if not isinstance(row.get("storageField"), str) or not row["storageField"]:
            raise TableError("field %d has invalid storageField" % row["id"])
    return table


def banner():
    return ("/* generated, do not edit.\n"
            " * Generated by gen_playable_properties.py from "
            "harken_playable_property_table.json.\n"
            " * Regenerate: %s\n"
            " */\n\n" % REGEN)


def enum_block(name, values):
    rows = ["enum class %s : std::uint8_t {\n" % name]
    for index, value in enumerate(values):
        rows.append("    %s = %d,\n" % (enum_name(value), index))
    rows.append("};\n\n")
    return "".join(rows)


def emit_shared_enums():
    return (enum_block("PlayablePropertyPresenceV1", ["maskBit"]) +
            enum_block("PlayablePropertyWireV1", WIRES) +
            enum_block("PlayablePropertyCombineRoleV1", COMBINES) +
            enum_block("PlayablePropertyReferenceRoleV1", REFERENCES) +
            enum_block("PlayablePropertyCapabilityRoleV1", CAPABILITIES) +
            enum_block("PlayablePropertyPhaseRoleV1", PHASES) +
            enum_block("PlayablePropertyDefaultV1", DEFAULTS))


def emit_project(table):
    out = [banner(), "#ifndef HARKEN_PLAYABLE_PROPERTIES_GENERATED_PROJECT_G_H\n",
           "#define HARKEN_PLAYABLE_PROPERTIES_GENERATED_PROJECT_G_H\n\n",
           "#include <cstdint>\n#include <iterator>\n\n",
           "namespace harkenplayableproperties {\n\n"]
    out.append("enum class ContentPropertyKindV1 : std::uint8_t {\n")
    for row in table["contentKinds"]:
        out.append("    %s = %d,\n" % (row["name"], row["ordinal"]))
    out.append("};\n\n")
    out.append("enum class PlayablePropertyIdV1 : std::uint8_t {\n")
    for row in table["fields"]:
        out.append("    %s = %d,\n" % (enum_name(row["name"]), row["id"]))
    out.append("};\n\n")
    out.append(emit_shared_enums())
    out.append("inline constexpr std::uint64_t kPlayablePropertyKnownMaskV1 = "
               "UINT64_C(0x000000000001afff);\n\n")
    out.append("struct ChassisPresenceV1 {\n"
               "    std::uint64_t bits = 0;\n"
               "    constexpr bool IsValid() const noexcept {\n"
               "        return (bits & ~kPlayablePropertyKnownMaskV1) == 0;\n"
               "    }\n"
               "    constexpr bool Has(PlayablePropertyIdV1 id) const noexcept {\n"
               "        const auto ordinal = static_cast<std::uint8_t>(id);\n"
               "        return ordinal >= 1 && ordinal <= 17 && ordinal != 13 && ordinal != 15 &&\n"
               "               (bits & (UINT64_C(1) << (ordinal - 1))) != 0;\n"
               "    }\n"
               "    constexpr void Set(PlayablePropertyIdV1 id) noexcept {\n"
               "        const auto ordinal = static_cast<std::uint8_t>(id);\n"
               "        if (ordinal >= 1 && ordinal <= 17 && ordinal != 13 && ordinal != 15) bits |= UINT64_C(1) << (ordinal - 1);\n"
               "    }\n"
               "    constexpr void Clear(PlayablePropertyIdV1 id) noexcept {\n"
               "        const auto ordinal = static_cast<std::uint8_t>(id);\n"
               "        if (ordinal >= 1 && ordinal <= 17 && ordinal != 13 && ordinal != 15) bits &= ~(UINT64_C(1) << (ordinal - 1));\n"
               "    }\n"
               "};\n\n")
    out.append("struct PlayablePropertyMetaV1 {\n"
               "    PlayablePropertyIdV1 id; std::uint64_t presentBit; const char* name; const char* jsonKey;\n"
               "    PlayablePropertyWireV1 wire; PlayablePropertyPresenceV1 presence;\n"
               "    PlayablePropertyCombineRoleV1 combineRole;\n"
               "    PlayablePropertyReferenceRoleV1 referenceRole;\n"
               "    PlayablePropertyCapabilityRoleV1 capabilityRole;\n"
               "    PlayablePropertyPhaseRoleV1 phaseRole; PlayablePropertyDefaultV1 canonicalDefault;\n"
               "};\n\ninline constexpr PlayablePropertyMetaV1 kPlayablePropertyRegistryV1[] = {\n")
    for row in table["fields"]:
        out.append("    {PlayablePropertyIdV1::%s, UINT64_C(0x%016x), \"%s\", \"%s\", PlayablePropertyWireV1::%s, PlayablePropertyPresenceV1::MaskBit, PlayablePropertyCombineRoleV1::%s, PlayablePropertyReferenceRoleV1::%s, PlayablePropertyCapabilityRoleV1::%s, PlayablePropertyPhaseRoleV1::%s, PlayablePropertyDefaultV1::%s},\n" %
                   (enum_name(row["name"]), 1 << (row["id"] - 1), row["name"], row["jsonKey"],
                    enum_name(row["wire"]), enum_name(row["combineRole"]),
                    enum_name(row["referenceRole"]), enum_name(row["capabilityRole"]),
                    enum_name(row["phaseRole"]), enum_name(row["canonicalDefault"])))
    out.append("};\nstatic_assert(std::size(kPlayablePropertyRegistryV1) == 15);\n"
               "static_assert(sizeof(ChassisPresenceV1) == sizeof(std::uint64_t));\n\n"
               "} // namespace harkenplayableproperties\n\n"
               "#endif // HARKEN_PLAYABLE_PROPERTIES_GENERATED_PROJECT_G_H\n")
    return "".join(out)


def emit_runtime(table, namespace="harken",
                 guard="HARKEN_CORE_GENERATED_PLAYABLE_PROPERTY_RUNTIME_G_H"):
    out = [banner(), "#ifndef %s\n" % guard,
           "#define %s\n\n" % guard,
           "#include <cstdint>\n#include <iterator>\n\n",
           "namespace %s { namespace playableproperties {\n\n" % namespace,
           "enum class ContentPropertyKindV1 : std::uint8_t { Layer = 0, Sound = 1, Container = 2, Track = 3, Segment = 4 };\n\n",
           "enum class PlayablePropertyIdV1 : std::uint8_t {\n"]
    for row in table["fields"]:
        out.append("    %s = %d,\n" % (enum_name(row["name"]), row["id"]))
    out.extend(["};\n\n",
           emit_shared_enums(),
           "inline constexpr std::uint32_t kPlayablePropertyRegistryVintageV1 = 1;\n",
           "inline constexpr std::uint64_t kPlayablePropertyKnownMaskV1 = UINT64_C(0x000000000001afff);\n\n",
           "struct RuntimePropertyMetaV1 { PlayablePropertyIdV1 id; std::uint64_t presentBit; const char* name; PlayablePropertyWireV1 wire; PlayablePropertyPresenceV1 presence; PlayablePropertyCombineRoleV1 combineRole; PlayablePropertyReferenceRoleV1 referenceRole; PlayablePropertyCapabilityRoleV1 capabilityRole; PlayablePropertyPhaseRoleV1 phaseRole; PlayablePropertyDefaultV1 canonicalDefault; };\n\n",
           "inline constexpr RuntimePropertyMetaV1 kRuntimeAndVtrcPropertyTableV1[] = {\n"])
    for row in table["fields"]:
        out.append("    {PlayablePropertyIdV1::%s, UINT64_C(0x%016x), \"%s\", PlayablePropertyWireV1::%s, PlayablePropertyPresenceV1::MaskBit, PlayablePropertyCombineRoleV1::%s, PlayablePropertyReferenceRoleV1::%s, PlayablePropertyCapabilityRoleV1::%s, PlayablePropertyPhaseRoleV1::%s, PlayablePropertyDefaultV1::%s},\n" %
                   (enum_name(row["name"]), 1 << (row["id"] - 1), row["name"], enum_name(row["wire"]),
                    enum_name(row["combineRole"]), enum_name(row["referenceRole"]),
                    enum_name(row["capabilityRole"]), enum_name(row["phaseRole"]),
                    enum_name(row["canonicalDefault"])))
    out.append("};\nstatic_assert(std::size(kRuntimeAndVtrcPropertyTableV1) == 15);\n\n"
               "} } // namespace %s::playableproperties\n\n"
               "#endif // %s\n" % (namespace, guard))
    return "".join(out)


def emit_studio(table):
    out = [banner(), "#ifndef HARKEN_PLAYABLE_PROPERTIES_GENERATED_STUDIO_G_H\n",
           "#define HARKEN_PLAYABLE_PROPERTIES_GENERATED_STUDIO_G_H\n\n",
           "#include \"harken_playable_properties.g.h\"\n\n",
           "#include <cstdint>\n#include <iterator>\n\n",
           "namespace harkenplayableproperties { namespace studio {\n\n",
           "inline constexpr char kEnvelopeJsonKeyV1[] = \"playableProperties\";\n",
           "inline constexpr char kPresenceJsonKeyV1[] = \"presence\";\n\n",
           "struct JsonFieldV1 { std::uint8_t id; std::uint64_t presentBit; PlayablePropertyWireV1 wire; PlayablePropertyDefaultV1 canonicalDefault; PlayablePropertyReferenceRoleV1 referenceRole; const char* component; const char* storageField; const char* fieldName; const char* jsonKey; };\n\n",
           "inline constexpr JsonFieldV1 kJsonFieldsV1[] = {\n"]
    for row in table["fields"]:
        out.append("    {%d, UINT64_C(0x%016x), PlayablePropertyWireV1::%s, PlayablePropertyDefaultV1::%s, PlayablePropertyReferenceRoleV1::%s, \"%s\", \"%s\", \"%s\", \"%s\"},\n" %
                   (row["id"], 1 << (row["id"] - 1), enum_name(row["wire"]),
                    enum_name(row["canonicalDefault"]), enum_name(row["referenceRole"]), row["component"],
                    row["storageField"], row["name"], row["jsonKey"]))
    out.append("};\nstatic_assert(std::size(kJsonFieldsV1) == 15);\n\n"
               "} } // namespace harkenplayableproperties::studio\n\n"
               "#endif // HARKEN_PLAYABLE_PROPERTIES_GENERATED_STUDIO_G_H\n")
    return "".join(out)


def manifest(table):
    return json.dumps(table, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def parse_args(argv):
    parser = argparse.ArgumentParser(allow_abbrev=False)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(sys.argv[1:] if argv is None else argv)
    try:
        table = load_table()
    except (OSError, ValueError, KeyError, TableError) as error:
        sys.stderr.write("%s: %s\n" % (SOURCE, error))
        return 1
    outputs = {
        os.path.join(CONTRACT_OUT, "harken_playable_properties.g.h"): emit_project(table),
        os.path.join(CONTRACT_OUT, "harken_playable_property_studio.g.h"): emit_studio(table),
        os.path.join(CONTRACT_OUT, "harken_playable_property_manifest.g.json"): manifest(table),
        os.path.join(RUNTIME_OUT, "harken_playable_property_runtime.g.h"): emit_runtime(table),
        os.path.join(PACK_BUILD_OUT, "Properties.h"): emit_runtime(
            table, "harkenstudiobuild",
            "HARKEN_STUDIO_BUILD_GENERATED_PLAYABLE_PROPERTY_RUNTIME_G_H"),
    }
    failed = False
    for path, content in sorted(outputs.items()):
        if args.check:
            read_error = None
            try:
                with open(path, "r", encoding="utf-8", newline="") as handle:
                    if handle.read() == content:
                        continue
            except OSError as error:
                read_error = error
            detail = "" if read_error is None else "; read failed: %s" % read_error
            sys.stderr.write("%s: stale or missing%s; run: %s\n" %
                             (path, detail, REGEN))
            failed = True
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="") as handle:
                handle.write(content)
            print("wrote %s" % path)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
