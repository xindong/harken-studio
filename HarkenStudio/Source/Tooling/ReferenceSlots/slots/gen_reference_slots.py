"""Generate the reference-slot vocabulary from harken_reference_slot_table.json.

The slot ordinals and their target kinds were written by hand in three places:
the compile-side resolver's enumeration, the runtime ticket's enumeration, and
the runtime's kind-to-validation mapping. Three hand-written copies of one
numbering is one numbering that can disagree with itself, and a program built
against one copy and read against another resolves to the wrong kind of target
entirely. So the table is the single source and all three are emitted from it.

Outputs are checked in, so an ordinary build never needs Python:

    py -3 HarkenStudio/Source/Tooling/ReferenceSlots/slots/gen_reference_slots.py
    py -3 HarkenStudio/Source/Tooling/ReferenceSlots/slots/gen_reference_slots.py --check

--check recomputes every output and compares it byte for byte without writing,
which is what the contract check in the test suite runs.
"""

import argparse
import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
TABLE_PATH = os.path.join(SCRIPT_DIR, "harken_reference_slot_table.json")
TOOLING_GENERATED_DIR = os.path.normpath(
    os.path.join(SCRIPT_DIR, "..", "generated"))
RUNTIME_GENERATED_DIR = os.path.normpath(
    os.path.join(SCRIPT_DIR, "..", "..", "..", "..", "..", "HarkenEngine", "Source", "Runtime", "media", "include",
                 "harken", "media", "generated"))

REGEN_COMMAND = ("py -3 HarkenStudio/Source/Tooling/ReferenceSlots/slots/"
                 "gen_reference_slots.py")

# Every target kind the table may name, and its runtime enumerator and ordinal.
# A kind outside this set is refused rather than passed through, because an
# unrecognized kind would emit a table row the runtime cannot dispatch on.
TARGET_KINDS = {
    "bus": ("Bus", 2),
    "attenuation": ("Attenuation", 0),
}


class TableError(Exception):
    """The table is not usable. Raised instead of emitting partial output."""


def pascal_case(name):
    """`outputBus` -> `OutputBus`. Enumerators are the table's names, cased."""
    if not name:
        raise TableError("a name may not be empty")
    return name[0].upper() + name[1:]


def validate_rows(rows, what, first_ordinal):
    """Checks the shared shape of the slot and level row lists.

    Ordinals must be unique and contiguous from first_ordinal, because both
    generated tables are indexed by ordinal: a gap would produce a row nobody
    can address, and a duplicate would silently drop one of the two. Names must
    be unique because they become enumerator spellings.
    """
    if not rows:
        raise TableError("%s must have at least one entry" % what)
    ordinals = [row["ordinal"] for row in rows]
    names = [row["name"] for row in rows]
    if len(set(ordinals)) != len(ordinals):
        raise TableError("%s ordinals must be unique" % what)
    if len(set(names)) != len(names):
        raise TableError("%s names must be unique" % what)
    expected = list(range(first_ordinal, first_ordinal + len(rows)))
    if sorted(ordinals) != expected:
        raise TableError(
            "%s ordinals must be contiguous from %d; got %s"
            % (what, first_ordinal, sorted(ordinals)))
    for row in rows:
        if not isinstance(row["ordinal"], int) or isinstance(
                row["ordinal"], bool):
            raise TableError("%s ordinals must be integers" % what)
        if not isinstance(row["name"], str) or not row["name"]:
            raise TableError("%s names must be non-empty strings" % what)


def load_table():
    with open(TABLE_PATH, "r", encoding="utf-8") as handle:
        table = json.load(handle)

    vintage = table.get("vintage")
    if not isinstance(vintage, int) or isinstance(vintage, bool) or vintage < 1:
        raise TableError("vintage must be a positive integer")

    slots = table.get("slots")
    levels = table.get("levels")
    if not isinstance(slots, list) or not isinstance(levels, list):
        raise TableError("the table needs a slots list and a levels list")

    # Slots are ordinal 0 upward because they are compiled into programs;
    # levels start at 1 because 0 would collide with "no level recorded".
    validate_rows(slots, "slot", 0)
    validate_rows(levels, "level", 1)

    for slot in slots:
        kind = slot.get("targetKind")
        if kind not in TARGET_KINDS:
            raise TableError(
                "slot '%s' has target kind '%s'; allowed: %s"
                % (slot["name"], kind, ", ".join(sorted(TARGET_KINDS))))

    return {
        "vintage": vintage,
        "slots": sorted(slots, key=lambda row: row["ordinal"]),
        "levels": sorted(levels, key=lambda row: row["ordinal"]),
    }


def banner(generated_from):
    return ("/* generated, do not edit.\n"
            " * Generated by gen_reference_slots.py from %s.\n"
            " * Regenerate: %s\n"
            " */\n"
            "\n" % (generated_from, REGEN_COMMAND))


def emit_compile_header(table):
    """The vocabulary the resolver reasons in: slots, levels, and slot names.

    Target kinds are deliberately absent. The resolver decides which level won
    and knows nothing about what a value points at; giving it target kinds would
    hand it knowledge it must not act on.
    """
    lines = [banner("harken_reference_slot_table.json")]
    lines.append("#ifndef HARKEN_REFERENCE_SLOTS_GENERATED_SLOTS_G_H\n"
                 "#define HARKEN_REFERENCE_SLOTS_GENERATED_SLOTS_G_H\n"
                 "\n"
                 "#include <cstdint>\n"
                 "#include <iterator>\n"
                 "\n"
                 "namespace harkenreferenceslots {\n"
                 "\n")
    lines.append("// Vintage of the table these definitions came from. A program\n"
                 "// compiled against one vintage and read against another resolves\n"
                 "// to the wrong kind of target, so the number travels with the\n"
                 "// compiled shape rather than being assumed.\n"
                 "inline constexpr std::uint32_t kReferenceSlotTableVintage = %d;\n"
                 "\n" % table["vintage"])

    lines.append("// The reference slots. Ordinals are part of the compiled shape\n"
                 "// and are append-only.\n"
                 "enum class ReferenceSlot : std::uint32_t {\n")
    for slot in table["slots"]:
        lines.append("    %s = %d,\n" % (pascal_case(slot["name"]),
                                         slot["ordinal"]))
    lines.append("};\n\n")
    lines.append("inline constexpr std::uint32_t kReferenceSlotCount = %d;\n\n"
                 % len(table["slots"]))

    lines.append("// Where a resolved value came from. Numbered by descending\n"
                 "// precedence, so a smaller value always wins.\n"
                 "enum class ResolutionLevel : std::uint32_t {\n")
    for level in table["levels"]:
        lines.append("    %s = %d,\n" % (pascal_case(level["name"]),
                                         level["ordinal"]))
    lines.append("};\n\n")
    lines.append("inline constexpr std::uint32_t kResolutionLevelCount = %d;\n\n"
                 % len(table["levels"]))

    lines.append("// One slot's documented facts. The name is the stable spelling\n"
                 "// diagnostics and explain output use.\n"
                 "struct ReferenceSlotMeta {\n"
                 "    ReferenceSlot slot;\n"
                 "    const char* name;\n"
                 "};\n\n")
    lines.append("inline constexpr ReferenceSlotMeta kReferenceSlotTable[] = {\n")
    for slot in table["slots"]:
        lines.append("    {ReferenceSlot::%s, \"%s\"},\n"
                     % (pascal_case(slot["name"]), slot["name"]))
    lines.append("};\n\n")

    lines.append("static_assert(std::size(kReferenceSlotTable) ==\n"
                 "                  kReferenceSlotCount,\n"
                 "              \"every reference slot needs exactly one table row\");\n")
    for index, slot in enumerate(table["slots"]):
        lines.append("static_assert(kReferenceSlotTable[%d].slot ==\n"
                     "                  ReferenceSlot::%s,\n"
                     "              \"reference slot rows must stay in ordinal order\");\n"
                     % (index, pascal_case(slot["name"])))

    # The precedence invariant is asserted rather than described, so a level
    # renumbered in the table breaks the build instead of silently changing
    # which authored value wins.
    lines.append("\n")
    for earlier, later in zip(table["levels"], table["levels"][1:]):
        lines.append("static_assert(static_cast<std::uint32_t>(ResolutionLevel::%s) <\n"
                     "                  static_cast<std::uint32_t>(ResolutionLevel::%s),\n"
                     "              \"precedence levels must ascend as they weaken\");\n"
                     % (pascal_case(earlier["name"]), pascal_case(later["name"])))
    lines.append("static_assert(static_cast<std::uint32_t>(ResolutionLevel::%s) ==\n"
                 "                  kResolutionLevelCount,\n"
                 "              \"the weakest level must be the last ordinal\");\n"
                 % pascal_case(table["levels"][-1]["name"]))

    lines.append("\n} // namespace harkenreferenceslots\n"
                 "\n"
                 "#endif // HARKEN_REFERENCE_SLOTS_GENERATED_SLOTS_G_H\n")
    return "".join(lines)


def emit_wire_header(table):
    """The Pack candidate wire contract: ordinal plus target kind per slot.

    Nothing consumes this yet. The pack compiler's manifest has no reference-slot
    section, and the editor does not emit one, so this header states the contract
    the two would have to agree on rather than describing a format in use. It is
    generated now so that when either side is wired the numbering is already
    fixed by the same table the resolver uses, instead of being invented a second
    time at that point.
    """
    lines = [banner("harken_reference_slot_table.json")]
    lines.append("#ifndef HARKEN_REFERENCE_SLOTS_GENERATED_WIRE_G_H\n"
                 "#define HARKEN_REFERENCE_SLOTS_GENERATED_WIRE_G_H\n"
                 "\n"
                 "#include <cstdint>\n"
                 "#include <iterator>\n"
                 "\n"
                 "namespace harkenreferenceslots {\n"
                 "namespace wire {\n"
                 "\n")
    lines.append("// Vintage a program records so a reader can refuse a numbering it\n"
                 "// does not share. No consumer writes it yet; see the header note.\n"
                 "inline constexpr std::uint32_t kSlotWireVintage = %d;\n"
                 "\n" % table["vintage"])

    lines.append("// What a resolved value points at, which is what decides the\n"
                 "// existence check a reader has to run.\n"
                 "enum class TargetKind : std::uint32_t {\n")
    for name in sorted(TARGET_KINDS):
        lines.append("    %s = %d,\n" % TARGET_KINDS[name])
    lines.append("};\n\n")

    lines.append("// One slot as it crosses into a compiled program.\n"
                 "struct SlotRow {\n"
                 "    std::uint32_t ordinal;\n"
                 "    const char* name;\n"
                 "    TargetKind targetKind;\n"
                 "};\n\n")
    lines.append("inline constexpr SlotRow kSlotRows[] = {\n")
    for slot in table["slots"]:
        lines.append("    {%d, \"%s\", TargetKind::%s},\n"
                     % (slot["ordinal"], slot["name"],
                        TARGET_KINDS[slot["targetKind"]][0]))
    lines.append("};\n\n")
    lines.append("inline constexpr std::uint32_t kSlotRowCount = %d;\n\n"
                 % len(table["slots"]))
    lines.append("static_assert(std::size(kSlotRows) == kSlotRowCount,\n"
                 "              \"every slot needs exactly one wire row\");\n")
    for index, slot in enumerate(table["slots"]):
        lines.append("static_assert(kSlotRows[%d].ordinal == %d,\n"
                     "              \"wire rows must stay in ordinal order\");\n"
                     % (index, slot["ordinal"]))

    lines.append("\n} // namespace wire\n"
                 "} // namespace harkenreferenceslots\n"
                 "\n"
                 "#endif // HARKEN_REFERENCE_SLOTS_GENERATED_WIRE_G_H\n")
    return "".join(lines)


def emit_runtime_header(table):
    """The runtime's slot enumeration and its kind-to-validation mapping.

    The runtime dispatches on the target kind read from this table rather than on
    a hand-written mapping per slot, so adding a slot cannot leave a validation
    path unwritten while every existing check still passes.
    """
    lines = [banner("HarkenStudio/Source/Tooling/ReferenceSlots/slots/"
                    "harken_reference_slot_table.json")]
    lines.append("#ifndef HARKEN_MEDIA_GENERATED_RESOLVED_SLOT_KINDS_G_H\n"
                 "#define HARKEN_MEDIA_GENERATED_RESOLVED_SLOT_KINDS_G_H\n"
                 "\n"
                 "#include <cstdint>\n"
                 "#include <iterator>\n"
                 "\n"
                 "namespace harken {\n"
                 "\n")
    lines.append("// Vintage of the slot numbering this runtime understands. A\n"
                 "// program recording a different one names slots this build would\n"
                 "// resolve to other kinds of target.\n"
                 "inline constexpr std::uint32_t kResolvedSlotTableVintage = %d;\n"
                 "\n" % table["vintage"])

    lines.append("// Slot ordinals as they appear in a compiled program.\n"
                 "enum class ResolvedSlotKind : std::uint32_t {\n")
    for slot in table["slots"]:
        lines.append("    %s = %d,\n" % (pascal_case(slot["name"]),
                                         slot["ordinal"]))
    lines.append("};\n\n")
    lines.append("inline constexpr std::uint32_t kResolvedSlotKindCount = %d;\n\n"
                 % len(table["slots"]))

    lines.append("// What a slot's value points at. The runtime picks its existence\n"
                 "// check from this rather than from a mapping written per slot.\n"
                 "enum class ResolvedSlotTargetKind : std::uint32_t {\n")
    for name in sorted(TARGET_KINDS):
        lines.append("    %s = %d,\n" % TARGET_KINDS[name])
    lines.append("};\n\n")

    lines.append("struct ResolvedSlotKindRow {\n"
                 "    ResolvedSlotKind kind;\n"
                 "    ResolvedSlotTargetKind targetKind;\n"
                 "    const char* name;\n"
                 "};\n\n")
    lines.append("inline constexpr ResolvedSlotKindRow kResolvedSlotKindTable[] = {\n")
    for slot in table["slots"]:
        lines.append("    {ResolvedSlotKind::%s, ResolvedSlotTargetKind::%s,\n"
                     "     \"%s\"},\n"
                     % (pascal_case(slot["name"]),
                        TARGET_KINDS[slot["targetKind"]][0], slot["name"]))
    lines.append("};\n\n")
    lines.append("static_assert(std::size(kResolvedSlotKindTable) ==\n"
                 "                  kResolvedSlotKindCount,\n"
                 "              \"every resolved slot kind needs exactly one row\");\n")
    for index, slot in enumerate(table["slots"]):
        lines.append("static_assert(kResolvedSlotKindTable[%d].kind ==\n"
                     "                  ResolvedSlotKind::%s,\n"
                     "              \"resolved slot rows must stay in ordinal order\");\n"
                     % (index, pascal_case(slot["name"])))

    lines.append("\n// The row for one slot kind, or nullptr for an ordinal this build\n"
                 "// does not define. A caller gets a refusal rather than a guess.\n"
                 "inline const ResolvedSlotKindRow* FindResolvedSlotKind(\n"
                 "    ResolvedSlotKind kind) {\n"
                 "    for (const ResolvedSlotKindRow& row : kResolvedSlotKindTable) {\n"
                 "        if (row.kind == kind) {\n"
                 "            return &row;\n"
                 "        }\n"
                 "    }\n"
                 "    return nullptr;\n"
                 "}\n")

    lines.append("\n} // namespace harken\n"
                 "\n"
                 "#endif // HARKEN_MEDIA_GENERATED_RESOLVED_SLOT_KINDS_G_H\n")
    return "".join(lines)


def parse_args(argv):
    """Parses the command line, rejecting anything not understood.

    Membership-testing sys.argv for "--check" treats every misspelling as "no
    mode requested", so a step asking for --chek would silently regenerate
    instead of verifying: a gate that passes precisely when it should fail, and
    that rewrites the checked-in outputs it exists to police. argparse with
    allow_abbrev disabled refuses the typo instead.
    """
    parser = argparse.ArgumentParser(
        prog="gen_reference_slots.py",
        description="Generate or verify the reference-slot vocabulary "
                    "generated from harken_reference_slot_table.json.",
        allow_abbrev=False)
    parser.add_argument(
        "--check", action="store_true",
        help="verify the checked-in outputs match the table without "
             "rewriting them")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(sys.argv[1:] if argv is None else argv)
    try:
        table = load_table()
    except TableError as error:
        sys.stderr.write("%s: %s\n" % (TABLE_PATH, error))
        return 1

    outputs = {
        os.path.join(TOOLING_GENERATED_DIR, "harken_reference_slots.g.h"):
            emit_compile_header(table),
        os.path.join(TOOLING_GENERATED_DIR, "harken_reference_slot_wire.g.h"):
            emit_wire_header(table),
        os.path.join(RUNTIME_GENERATED_DIR, "harken_resolved_slot_kinds.g.h"):
            emit_runtime_header(table),
    }

    failed = False
    for path in sorted(outputs):
        content = outputs[path]
        if args.check:
            try:
                with open(path, "r", encoding="utf-8", newline="") as handle:
                    existing = handle.read()
            except OSError:
                sys.stderr.write("%s: missing generated output\n" % path)
                failed = True
                continue
            if existing != content:
                sys.stderr.write(
                    "%s: does not match the table; run: %s\n"
                    % (path, REGEN_COMMAND))
                failed = True
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # newline="" keeps the emitted "\n" exactly as written, so the outputs
        # are byte-identical on every platform and --check cannot fail purely
        # because of where it ran.
        with open(path, "w", encoding="utf-8", newline="") as handle:
            handle.write(content)
        print("wrote %s" % path)

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
