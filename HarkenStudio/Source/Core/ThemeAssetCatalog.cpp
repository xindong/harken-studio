const ThemeAssetCatalogEntry* findThemeAssetCatalogEntry(const QString& logicalId)
{
    const auto& entries = themeAssetCatalog();
    for (const auto& entry : entries) {
        if (entry.logicalId == logicalId)
            return &entry;
    }
    return nullptr;
}

