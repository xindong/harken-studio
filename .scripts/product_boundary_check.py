#!/usr/bin/env python3
"""Report dependencies that cross product partitions.

Each top-level ``Harken*`` directory is a product. A product may reach another
product only through the edges listed in ``ALLOWED_EDGES``; everything else is
reported. The repository root CMake and ``cmake/`` are shared infrastructure and
may only select products, never carry their logic.

  python .scripts/product_boundary_check.py [--json-out PATH] [--strict]
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath
from typing import NamedTuple


REPO_ROOT = Path(__file__).resolve().parents[1]

PRODUCTS = (
    "HarkenEngine",
    "HarkenStudio",
    "HarkenIntegration",
    "HarkenHub",
)

PACK_FORMAT_INCLUDE_PREFIX = "harken_pack/"
ENGINE_PUBLIC_HEADER_NAMES = ("Harken.h", "HarkenDevelopment.h")

ALLOWED_EDGES = {
    ("HarkenStudio", "HarkenEngine"): {
        "targets": {"Harken::EngineDev", "Harken::PackFormat"},
        "paths": ("HarkenEngine/Format/Pack/",),
        "public_headers": True,
    },
    ("HarkenIntegration", "HarkenEngine"): {
        "targets": {"Harken::Engine", "Harken::EngineDev"},
        "paths": (),
        "public_headers": True,
    },
    ("HarkenIntegration", "HarkenStudio"): {
        "targets": set(),
        "paths": ("HarkenStudio/Format/PackMetadata/",),
        "public_headers": False,
    },
}

EXEMPTIONS = {
    ("root-product-logic", "cmake/BuildInfo.cmake", "HarkenHub"),
}

ROOT_SWITCH_OWNERS = (
    (re.compile(r"^HARKEN_BUILD_(EDITOR|STUDIO)"), "HarkenStudio"),
    (re.compile(r"^HARKEN_BUILD_HUB"), "HarkenHub"),
    (re.compile(r"^HARKEN_BUILD_INTEGRATION"), "HarkenIntegration"),
    (re.compile(r"^HARKEN_(BUILD_(CORE|SHARED|TOOLS|RUNTIME|RT_|ENGINE)|RT_PROBE_)"),
     "HarkenEngine"),
)

CMAKE_TARGET_COMMANDS = {
    "target_link_libraries",
    "add_dependencies",
}
CMAKE_DEFINING_COMMANDS = {"add_library", "add_executable", "add_custom_target"}
BUILD_DESCRIPTION_SUFFIXES = (".csproj", ".props", ".targets", ".asmdef")
SOURCE_SUFFIXES = (".h", ".hpp", ".hh", ".hxx", ".inl", ".c", ".cc", ".cpp",
                   ".cxx", ".mm", ".m")
INCLUDE_RE = re.compile(r'^\s*#\s*(?:include|import)\s*[<"]([^>"]+)[>"]', re.M)
IDENT_RE = re.compile(r"\bHARKEN_[A-Z0-9_]+\b")
GENERATED_BY_RE = re.compile(r"Generated by\s+([\w./\\-]+\.py)")


class Violation(NamedTuple):
    check: str
    source: str
    line: int
    owner: str
    target: str
    detail: str


def product_of(path: str) -> str | None:
    head = path.split("/", 1)[0]
    return head if head in PRODUCTS else None


def edge(source: str, target: str) -> dict | None:
    return ALLOWED_EDGES.get((source, target))


def path_allowed(source: str, target_path: str,
                 public_headers: frozenset[str] = frozenset()) -> bool:
    target = product_of(target_path)
    if target is None or target == source:
        return True
    rules = edge(source, target)
    if rules is None:
        return False
    if rules["public_headers"] and target_path in public_headers:
        return True
    return any(target_path.startswith(prefix) for prefix in rules["paths"])


def is_engine_public_root(path: str) -> bool:
    if not path.startswith("HarkenEngine/"):
        return False
    if path.startswith("HarkenEngine/Format/Pack/"):
        return True
    return PurePosixPath(path).name in ENGINE_PUBLIC_HEADER_NAMES and "/include/" in path


def line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def strip_cmake_comments(text: str) -> str:
    out = []
    in_quote = False
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == '"' and (i == 0 or text[i - 1] != "\\"):
            in_quote = not in_quote
        if ch == "#" and not in_quote:
            bracket = re.match(r"#\[(=*)\[", text[i:])
            if bracket:
                end = text.find("]" + bracket.group(1) + "]", i)
                end = len(text) if end < 0 else end + len(bracket.group(1)) + 2
            else:
                end = text.find("\n", i)
                end = len(text) if end < 0 else end
            out.append("".join(c for c in text[i:end] if c == "\n"))
            i = end
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def cmake_commands(text: str):
    text = strip_cmake_comments(text)
    pattern = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")
    position = 0
    while True:
        match = pattern.search(text, position)
        if match is None:
            return
        depth = 1
        in_quote = False
        i = match.end()
        while i < len(text) and depth:
            if text[i] == '"' and text[i - 1] != "\\":
                in_quote = not in_quote
            elif not in_quote and text[i] == "(":
                depth += 1
            elif not in_quote and text[i] == ")":
                depth -= 1
            i += 1
        yield match.group(1).lower(), text[match.end():i - 1], line_of(text, match.start())
        position = i


def cmake_args(body: str) -> list[str]:
    return re.findall(r'"[^"]*"|[^\s"]+', body)


class Checker:
    def __init__(self, files: list[str], read):
        self.files = files
        self.read = read
        self.violations: list[Violation] = []
        self.header_index: dict[str, list[str]] = {}
        self.file_set = set(files)
        self.target_owner: dict[str, str] = {}
        self.ident_owner: dict[str, set[str]] = {}
        for path in files:
            if path.endswith((".h", ".hpp", ".hh", ".hxx", ".inl")):
                self.header_index.setdefault(PurePosixPath(path).name, []).append(path)
        self.public_headers = self.engine_public_closure()

    def engine_public_closure(self) -> frozenset[str]:
        pending = [p for p in self.files if is_engine_public_root(p)]
        seen = set(pending)
        while pending:
            path = pending.pop()
            for match in INCLUDE_RE.finditer(self.read(path)):
                for found in self.resolve_include(path, match.group(1)):
                    if found.startswith("HarkenEngine/") and found not in seen:
                        seen.add(found)
                        pending.append(found)
        return frozenset(seen)

    def report(self, *args) -> None:
        violation = Violation(*args)
        if (violation.check, violation.source, violation.target) not in EXEMPTIONS:
            self.violations.append(violation)

    def cmake_files(self) -> list[str]:
        return [p for p in self.files
                if p.endswith("CMakeLists.txt") or p.endswith(".cmake")]

    def index_cmake(self) -> None:
        for path in self.cmake_files():
            owner = product_of(path)
            for name, body, _ in cmake_commands(self.read(path)):
                args = cmake_args(body)
                if not args:
                    continue
                if name in CMAKE_DEFINING_COMMANDS and owner:
                    if "ALIAS" not in args:
                        self.target_owner.setdefault(args[0], owner)
                if name in {"option", "set"} and IDENT_RE.fullmatch(args[0]):
                    self.ident_owner.setdefault(args[0], set()).add(
                        owner or self.root_owner(args[0], args[1:]))
                if name == "set_target_properties" and "PROPERTIES" in args and owner:
                    props = args[args.index("PROPERTIES") + 1::2]
                    for prop in props:
                        if IDENT_RE.fullmatch(prop):
                            self.ident_owner.setdefault(prop, set()).add(owner)

    def root_owner(self, ident: str, values: list[str]) -> str:
        for pattern, product in ROOT_SWITCH_OWNERS:
            if pattern.search(ident):
                return product
        for value in values:
            for product in PRODUCTS:
                if f"/{product}" in value or value.strip('"').startswith(product):
                    return product
        return "shared"

    def check_cmake(self) -> None:
        for path in self.cmake_files():
            owner = product_of(path)
            text = self.read(path)
            if owner is None:
                self.check_root_cmake(path, text)
                continue
            for name, body, line in cmake_commands(text):
                args = cmake_args(body)
                if name in CMAKE_TARGET_COMMANDS:
                    for token in args[1:]:
                        target_owner = self.target_owner.get(token)
                        if target_owner and target_owner != owner:
                            self.report("cmake-target", path, line, owner,
                                        target_owner, token)
                        elif token.startswith("Harken::"):
                            rules = edge(owner, "HarkenEngine")
                            if owner != "HarkenEngine" and (
                                    rules is None or token not in rules["targets"]):
                                self.report("cmake-target", path, line, owner,
                                            "HarkenEngine", token)
                for other in PRODUCTS:
                    if other == owner:
                        continue
                    for match in re.finditer(rf"(?<![A-Za-z]){other}/[^\s\")]*|(?<![A-Za-z]){other}(?=[\s\")])", body):
                        if not path_allowed(owner, match.group(0), self.public_headers):
                            self.report("cmake-path", path, line, owner, other,
                                        match.group(0))
                for ident in sorted(set(IDENT_RE.findall(body))):
                    owners = self.ident_owner.get(ident, set())
                    foreign = owners - {owner, "shared"}
                    if owners and foreign and owner not in owners and "shared" not in owners:
                        self.report("cmake-variable", path, line, owner,
                                    ",".join(sorted(foreign)), ident)

    def check_root_cmake(self, path: str, text: str) -> None:
        conditions: list[str] = []
        for name, body, line in cmake_commands(text):
            if name == "if":
                conditions.append(body)
                continue
            if name in {"elseif"} and conditions:
                conditions[-1] = body
                continue
            if name == "endif" and conditions:
                conditions.pop()
                continue
            if name == "add_subdirectory":
                target = product_of(cmake_args(body)[0].strip('"'))
                if target is None:
                    continue
                for ident in IDENT_RE.findall(" ".join(conditions)):
                    for switch_owner in self.ident_owner.get(ident, set()):
                        if switch_owner not in {target, "shared"}:
                            self.report("root-selection", path, line, "shared",
                                        target, f"{body.strip()} under {ident}")
                continue
            if name in {"option", "foreach", "endforeach", "message", "else",
                        "function", "endfunction", "include", "project"}:
                continue
            for ident in sorted(set(IDENT_RE.findall(body))):
                for ident_owner in self.ident_owner.get(ident, set()):
                    if ident_owner in PRODUCTS and not ident.startswith("HARKEN_BUILD_"):
                        self.report("root-product-logic", path, line, "shared",
                                    ident_owner, f"{name}({ident})")
            for product in PRODUCTS:
                if re.search(rf"(?<![A-Za-z]){product}\b", body):
                    self.report("root-product-logic", path, line, "shared",
                                product, f"{name} references {product}")

    def resolve_include(self, source: str, include: str) -> list[str]:
        local = str(PurePosixPath(source).parent / include)
        local = normalize(local)
        if local in self.file_set:
            return [local]
        if include.startswith(PACK_FORMAT_INCLUDE_PREFIX):
            staged = "HarkenEngine/Format/Pack/" + include[len(PACK_FORMAT_INCLUDE_PREFIX):]
            return [staged] if staged in self.file_set else []
        suffix = "/" + include.lstrip("./")
        candidates = self.header_index.get(PurePosixPath(include).name, [])
        return [c for c in candidates if ("/" + c).endswith(suffix)]

    def check_includes(self) -> None:
        for path in self.files:
            owner = product_of(path)
            if owner is None or not path.endswith(SOURCE_SUFFIXES):
                continue
            text = self.read(path)
            for match in INCLUDE_RE.finditer(text):
                include = match.group(1)
                candidates = self.resolve_include(path, include)
                if not candidates or any(product_of(c) == owner for c in candidates):
                    continue
                if any(path_allowed(owner, c, self.public_headers) for c in candidates):
                    continue
                target = product_of(candidates[0]) or "shared"
                if target == "shared":
                    continue
                self.report("include", path, line_of(text, match.start()), owner,
                            target, f"{include} -> {candidates[0]}")

    def check_build_descriptions(self) -> None:
        for path in self.files:
            owner = product_of(path)
            if owner is None or not path.endswith(BUILD_DESCRIPTION_SUFFIXES + (".py",)):
                continue
            text = self.read(path)
            seen: set[tuple[int, str]] = set()
            for match in re.finditer(r'"([^"\n]*)"|\'([^\'\n]*)\'|>([^<\n]+)<', text):
                value = next(g for g in match.groups() if g is not None)
                value = value.replace("\\", "/")
                target_path = None
                if ".." in value:
                    target_path = normalize(str(PurePosixPath(path).parent / value))
                for product in PRODUCTS:
                    if product != owner and re.search(rf"(?<![A-Za-z]){product}/", value):
                        target_path = value[value.index(product + "/"):]
                if target_path is None:
                    continue
                target = product_of(target_path)
                if target is None or target == owner or path_allowed(owner, target_path, self.public_headers):
                    continue
                key = (line_of(text, match.start()), target_path)
                if key in seen:
                    continue
                seen.add(key)
                kind = "script-path" if path.endswith(".py") else "build-path"
                self.report(kind, path, key[0], owner, target, target_path)

    def check_generated(self) -> None:
        scripts: dict[str, list[str]] = {}
        for path in self.files:
            if path.endswith(".py"):
                scripts.setdefault(PurePosixPath(path).name, []).append(path)
        for path in self.files:
            name = PurePosixPath(path).name
            if ".g." not in name:
                continue
            owner = product_of(path)
            if owner is None:
                continue
            head = "\n".join(self.read(path).splitlines()[:6])
            match = GENERATED_BY_RE.search(head)
            if not match:
                continue
            generator = match.group(1).replace("\\", "/")
            located = [generator] if generator.lstrip("./") in self.file_set else []
            located = [g.lstrip("./") for g in located] if located else scripts.get(
                PurePosixPath(generator).name, [])
            for script in located:
                script_owner = product_of(script) or "shared"
                if script_owner != owner:
                    self.report("generator", path, 1, owner, script_owner, script)

    def run(self) -> list[Violation]:
        self.index_cmake()
        self.check_cmake()
        self.check_includes()
        self.check_build_descriptions()
        self.check_generated()
        unique = sorted(set(self.violations),
                        key=lambda v: (v.check, v.source, v.line, v.detail))
        return unique


def normalize(path: str) -> str:
    parts: list[str] = []
    for part in path.split("/"):
        if part in {"", "."}:
            continue
        if part == "..":
            if parts:
                parts.pop()
            continue
        parts.append(part)
    return "/".join(parts)


def tracked_files(root: Path) -> list[str]:
    output = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        check=True, capture_output=True).stdout.decode("utf-8")
    return sorted(p for p in output.split("\0") if p)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=str(REPO_ROOT))
    parser.add_argument("--json-out")
    parser.add_argument("--strict", action="store_true",
                        help="exit non-zero when any violation is found")
    args = parser.parse_args(argv)
    root = Path(args.root)

    def read(path: str) -> str:
        return (root / path).read_text(encoding="utf-8", errors="replace")

    violations = Checker(tracked_files(root), read).run()
    for v in violations:
        print(f"[{v.check}] {v.source}:{v.line} {v.owner} -> {v.target}: {v.detail}")
    print(f"{len(violations)} product boundary violation(s)")
    if args.json_out:
        out = Path(args.json_out)
        out = out if out.is_absolute() else root / out
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps([v._asdict() for v in violations], indent=2),
                       encoding="utf-8")
    return 1 if args.strict and violations else 0


if __name__ == "__main__":
    sys.exit(main())
