from __future__ import annotations

import unittest
from pathlib import Path

from script_loader import load_script_module


REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT = REPO_ROOT / ".scripts" / "product_boundary_check.py"
MODULE = load_script_module("product_boundary_check", SCRIPT)


def run(tree: dict[str, str]) -> set[tuple[str, str, str]]:
    checker = MODULE.Checker(sorted(tree), tree.__getitem__)
    return {(v.check, v.owner, v.target) for v in checker.run()}


ENGINE_CMAKE = "add_library(engine_private STATIC a.cpp)\n"


class ProductBoundaryCheckTest(unittest.TestCase):
    def test_foreign_private_target_is_reported(self) -> None:
        found = run({
            "HarkenEngine/CMakeLists.txt": ENGINE_CMAKE,
            "HarkenStudio/CMakeLists.txt":
                "target_link_libraries(studio PRIVATE engine_private)\n",
        })
        self.assertIn(("cmake-target", "HarkenStudio", "HarkenEngine"), found)

    def test_published_target_follows_allowed_edges(self) -> None:
        studio = run({
            "HarkenStudio/CMakeLists.txt":
                "target_link_libraries(studio PRIVATE Harken::EngineDev Harken::PackFormat)\n",
        })
        hub = run({
            "HarkenHub/CMakeLists.txt":
                "target_link_libraries(hub PRIVATE Harken::EngineDev)\n",
        })
        self.assertEqual(set(), studio)
        self.assertIn(("cmake-target", "HarkenHub", "HarkenEngine"), hub)

    def test_only_public_headers_cross_products(self) -> None:
        found = run({
            "HarkenEngine/Source/api/include/harken/Harken.h": "",
            "HarkenEngine/Source/core/include/harken/core/Private.h": "",
            "HarkenEngine/Format/Pack/include/harken/pack/Layout.h": "",
            "HarkenStudio/Source/Bridge/A.cpp":
                '#include "harken/Harken.h"\n#include "harken/pack/Layout.h"\n',
            "HarkenStudio/Source/Bridge/B.cpp": '#include "harken/core/Private.h"\n',
        })
        self.assertEqual({("include", "HarkenStudio", "HarkenEngine")}, found)

    def test_own_header_shadows_foreign_header(self) -> None:
        found = run({
            "HarkenEngine/include/harken/ObjectId.h": "",
            "HarkenStudio/include/harken/ObjectId.h": "",
            "HarkenStudio/Source/A.cpp": '#include "harken/ObjectId.h"\n',
        })
        self.assertEqual(set(), found)

    def test_foreign_switch_in_product_cmake_is_reported(self) -> None:
        found = run({
            "CMakeLists.txt": "option(HARKEN_BUILD_EDITOR \"\" OFF)\n",
            "HarkenEngine/CMakeLists.txt": "if(HARKEN_BUILD_EDITOR)\nendif()\n",
        })
        self.assertIn(("cmake-variable", "HarkenEngine", "HarkenStudio"), found)

    def test_product_selected_by_foreign_switch_is_reported(self) -> None:
        found = run({
            "CMakeLists.txt":
                "option(HARKEN_BUILD_TOOLS \"\" OFF)\n"
                "if(HARKEN_BUILD_TOOLS)\nadd_subdirectory(HarkenStudio/Tooling)\nendif()\n",
        })
        self.assertIn(("root-selection", "shared", "HarkenStudio"), found)

    def test_generator_must_live_with_its_output(self) -> None:
        found = run({
            "HarkenStudio/Tool/gen_table.py": "",
            "HarkenEngine/include/table.g.h": "// Generated by gen_table.py\n",
            "HarkenEngine/Tool/gen_own.py": "",
            "HarkenEngine/include/own.g.h": "// Generated by gen_own.py\n",
        })
        self.assertEqual({("generator", "HarkenEngine", "HarkenStudio")}, found)


if __name__ == "__main__":
    unittest.main()
