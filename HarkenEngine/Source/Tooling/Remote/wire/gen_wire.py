C_HEADER = (
    "/* generated, do not edit.\n"
    " * Generated by gen_wire.py from harken_wire_table.json.\n"
    " * Regenerate: py -3 HarkenEngine/Source/Tooling/Remote/wire/gen_wire.py\n"
    " */\n"
)
