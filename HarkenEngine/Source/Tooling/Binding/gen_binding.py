CS_HEADER = (
    "// generated, do not edit.\n"
    "// Generated by gen_binding.py from"
    " HarkenEngine/Source/Tooling/Remote/wire/harken_wire_table.json.\n"
    "// Regenerate: py -3 HarkenEngine/Source/Tooling/Binding/gen_binding.py\n"
)
CPP_HEADER = (
    "/* generated, do not edit.\n"
    " * Generated by gen_binding.py from"
    " HarkenEngine/Source/Tooling/Remote/wire/harken_wire_table.json.\n"
    " * Regenerate: py -3 HarkenEngine/Source/Tooling/Binding/gen_binding.py\n"
    " */\n"
)

NAMESPACE = "Harken"

CS_SCALAR = {"u8": "byte", "u16": "ushort", "u32": "uint", "u64": "ulong",
             "i32": "int", "f32": "float", "f64": "double"}

CS_RESERVED_KEYWORDS = frozenset("""
    abstract as base bool break byte case catch char checked class const continue
    decimal default delegate do double else enum event explicit extern false
    finally fixed float for foreach goto if implicit in int interface internal is
    lock long namespace new null object operator out override params private
    protected public readonly ref return sbyte sealed short sizeof stackalloc
    static string struct switch this throw true try typeof uint ulong unchecked
    unsafe ushort using virtual void volatile while
""".split())


def cs_scalar(kind):
    return CS_SCALAR[kind]


def cs_identifier(name):
    """Return a legal C# source identifier without changing its metadata name."""
    return "@" + name if name in CS_RESERVED_KEYWORDS else name


def union_field_name(member_type):
    """VnPlayStep -> play, VnSetValueStep -> setValue (the C union field name)."""
    core = member_type
    if core.startswith("Vn"):
        core = core[2:]
    if core.endswith("Step"):
        core = core[:-4]
    return core[:1].lower() + core[1:]


def struct_needs_unsafe(desc):
    """A struct needs `unsafe` iff it directly declares a fixed buffer, i.e.
    it has an array field (scalar array -> fixed <t>[]; struct array -> raw
    primitive fixed buffer). Embedding a struct that contains a fixed buffer
    does not itself require unsafe."""
    for _, spec in desc["fields"]:
        if isinstance(spec, dict) and "array" in spec:
            return True
    return False


def collect_unions(table):
    unions = []  # (union_struct_name, [member types])
    for name, desc in table["types"].items():
        for fname, spec in desc["fields"]:
            if isinstance(spec, dict) and "union" in spec:
                un = name + fname[:1].upper() + fname[1:]
                unions.append((un, spec["union"]))
    return unions


def emit_field(struct_name, fname, spec, layouts):
    """Returns (lines, cs_field_name) for one struct field. cs_field_name is
    the unescaped metadata name Marshal.OffsetOf must be given (usually ==
    fname; struct arrays get a Raw suffix because they lower to a raw primitive
    fixed buffer). Declarations use a verbatim identifier for C# keywords."""
    csn = fname
    if isinstance(spec, str):
        return (["    public %s %s;" % (cs_scalar(spec), cs_identifier(csn))], csn)
    if "array" in spec:
        elem, count = spec["array"]
        if isinstance(elem, str) and elem in gen_wire.SCALAR_SIZES:
            return (["    public fixed %s %s[%d];"
                     % (cs_scalar(elem), cs_identifier(csn), count)], csn)
        # Struct-element array: lower to a raw primitive fixed buffer sized to
        # the element footprint (C# fixed buffers accept only primitive types).
        sub = layouts[elem]
        if sub.align <= 4:
            cs_elem, unit = "uint", 4
        else:
            cs_elem, unit = "ulong", 8
        assert sub.size % unit == 0, "%s element %s not %d-divisible" % (
            fname, elem, unit)
        per = sub.size // unit
        csn += "Raw"
        return ([
            "    // %s[%d]: %d x %s (%d bytes each). Raw %s buffer — reinterpret"
            % (fname, count, count, elem, sub.size, cs_elem),
            "    // to a %s span to read (see the SDK snapshot reader)." % elem,
            "    public fixed %s %s[%d];"
            % (cs_elem, cs_identifier(csn), count * per),
        ], csn)
    if "struct" in spec:
        return (["    public %s %s;" % (spec["struct"], cs_identifier(csn))], csn)
    if "union" in spec:
        un = struct_name + fname[:1].upper() + fname[1:]
        return (["    public %s %s;" % (un, cs_identifier(csn))], csn)
    if "ptr" in spec:
        # Every C pointer (string, array, callback, void*, sample data) is a
        # blittable IntPtr in the mirror; the caller/SDK fills it. Keeps the
        # struct blittable and the hot path allocation-free.
        return (["    public IntPtr %s;" % cs_identifier(csn)], csn)
    raise ValueError("unknown field spec: %r" % (spec,))


def managed_projection(table, policy):
    rules = policy["managed_projection"]["excluded_prefixes"]
    projected = copy.deepcopy(table)
    keep = lambda category, name: not name.startswith(tuple(rules[category]))
    projected["types"] = {name: value for name, value in table["types"].items() if keep("types", name)}
    projected["api"]["enums"] = {name: value for name, value in table["api"]["enums"].items() if keep("types", name)}
    projected["api"]["callbacks"] = {name: value for name, value in table["api"]["callbacks"].items() if keep("types", name)}
    projected["api"]["defines"] = {name: value for name, value in table["api"]["defines"].items() if keep("constants", name)}
    projected["api"]["results"]["values"] = {
        name: value for name, value in table["api"]["results"]["values"].items() if keep("results", name)}
    for collection in ("functions", "binding_overloads"):
        projected[collection] = [fn for fn in table.get(collection, [])
                                 if keep("functions", fn["name"]) and keep("functions", fn.get("entryPoint", fn["name"]))]
    excluded = (set(table["types"]) - set(projected["types"])) | (set(table["api"]["enums"]) - set(projected["api"]["enums"])) | (
        set(table["api"]["callbacks"]) - set(projected["api"]["callbacks"]))

    def require_type(name, owner):
        if isinstance(name, str) and name in excluded:
            raise ValueError("SDK projection crosses excluded native type: %s -> %s" % (owner, name))

    def require_field(spec, owner):
        if isinstance(spec, str):
            require_type(spec, owner)
        elif isinstance(spec, dict):
            for kind, value in spec.items():
                if kind == "array":
                    require_field(value[0], owner)
                elif kind == "union":
                    for member in value:
                        require_field(member, owner)
                else:
                    require_field(value, owner)

    for name, desc in projected["types"].items():
        for _, spec in desc["fields"]:
            require_field(spec, name)
    callbacks = [entry for name, entry in projected["api"]["callbacks"].items() if not name.startswith("_")]
    for entry in projected["functions"] + projected["binding_overloads"] + callbacks:
        for param in entry.get("params", []):
            require_type(param.get("type"), entry.get("name", "callback"))
            require_type(param.get("ctype", "").replace("const ", "").rstrip(" *"), entry.get("name", "callback"))
    return projected


def managed_policy(table):
    """Require an audience for every generated symbol, independent of native ABI."""
    with open(SDK_POLICY_PATH, encoding="utf-8") as stream:
        policy = json.load(stream)
    table = managed_projection(table, policy)
    expected = {
        "types": {"VnResult", "VnConstants", "HarkenNative", "HarkenAbi"}
        | set(table["api"]["enums"]) | set(table["types"])
        | {name for name in table["api"]["callbacks"] if not name.startswith("_")}
        | {name for name, _ in collect_unions(table)},
        "constants": set(table["api"]["defines"]),
    }
    for category, names in expected.items():
        actual = set(policy.get("managed_generation", {}).get(category, {}))
        if actual != names:
            raise ValueError("Managed %s classification mismatch: missing=%s extra=%s" %
                             (category, sorted(names - actual), sorted(actual - names)))
        for name in names:
            managed_access(policy, category, name)
    return policy


def managed_access(policy, category, name):
    group = policy["groups"][policy["managed_generation"][category][name]]
    disposition = group["disposition"]
    if disposition not in {"supported", "compatibility", "move-internal"}:
        raise ValueError("Invalid managed disposition for " + name)
    return "internal" if disposition == "move-internal" else "public"


def emit_types(table, policy):
    layouts = gen_wire.compute_layouts(table["types"])
    api = table["api"]
    lines = [CS_HEADER]
    lines.append("using System;")
    lines.append("using System.Runtime.InteropServices;")
    lines.append("")
    lines.append("namespace %s" % NAMESPACE)
    lines.append("{")

    # Result code enum (int-backed; negative bands per Harken.h).
    lines.append("    /// <summary>Harken.h VnResult codes. 0 is success; negative"
                 " bands group error kinds.</summary>")
    lines.append("    %s enum VnResult : %s" % (managed_access(policy, "types", "VnResult"), cs_scalar(api["results"]["backing"])))
    lines.append("    {")
    for cname, value in api["results"]["values"].items():
        lines.append("        %s = %d," % (cname, value))
    lines.append("    }")
    lines.append("")

    # Public enums (members keep their exact C spelling for a 1:1 projection).
    for ename, edef in api["enums"].items():
        lines.append("    %s enum %s : %s" % (managed_access(policy, "types", ename), ename, cs_scalar(edef["backing"])))
        lines.append("    {")
        for cname, value in edef["values"].items():
            lines.append("        %s = %d," % (cname, value))
        lines.append("    }")
        lines.append("")

    # #define constants (a static holder; DllImport-safe compile-time values).
    lines.append("    /// <summary>Harken.h #define constants.</summary>")
    lines.append("    %s static class VnConstants" % managed_access(policy, "types", "VnConstants"))
    lines.append("    {")
    for cname, cdef in api["defines"].items():
        access = managed_access(policy, "constants", cname)
        if cdef["type"] == "objectid":
            value = cdef["value"]
            lines.append("        %s static readonly VnObjectId %s = new VnObjectId(%dUL, %dUL);" %
                         (access, cname, value["high"], value["low"]))
            continue
        cs = cs_scalar(cdef["type"])
        suffix = "UL" if cdef["type"] == "u64" else ("u" if cdef["type"].startswith("u") else "")
        lines.append("        %s const %s %s = %d%s;" % (access, cs, cname, cdef["value"], suffix))
    lines.append("    }")
    lines.append("")

    # Callback delegate types (AOT-safe: static handlers pass these; see the
    # SDK callback registry). Cdecl to match the extern-C engine exports.
    types = table["types"]
    for cbname, cbdef in api["callbacks"].items():
        if cbname.startswith("_"):
            continue
        ps = []
        for p in cbdef["params"]:
            ctype = p.get("ctype", "")
            is_ptr = ctype.rstrip().endswith("*")
            if not is_ptr and ctype in types:
                cty = ctype
            elif p["kind"] == "ptr":
                cty = "IntPtr"
            else:
                cty = cs_scalar(p["kind"])
            ps.append("%s %s" % (cty, cs_identifier(p["name"])))
        return_cs = cbdef.get("returnType", "void")
        lines.append("    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]")
        lines.append("    %s delegate %s %s(%s);" % (managed_access(policy, "types", cbname), return_cs, cbname, ", ".join(ps)))
        lines.append("")

    # Union payload structs (Explicit layout, every member overlapping at 0).
    for un, members in collect_unions(table):
        lines.append("    [StructLayout(LayoutKind.Explicit)]")
        lines.append("    %s struct %s" % (managed_access(policy, "types", un), un))
        lines.append("    {")
        for m in members:
            lines.append("        [FieldOffset(0)] public %s %s;"
                         % (m, cs_identifier(union_field_name(m))))
        lines.append("    }")
        lines.append("")

    # Blittable struct mirrors.
    for name, desc in table["types"].items():
        unsafe = " unsafe" if struct_needs_unsafe(desc) else ""
        if name == "VnObjectId":
            lines.append("    [Serializable]")
        lines.append("    [StructLayout(LayoutKind.Sequential)]")
        partial = " partial" if name == "VnObjectId" else ""
        lines.append("    %s%s%s struct %s" % (managed_access(policy, "types", name), unsafe, partial, name))
        lines.append("    {")
        for fname, spec in desc["fields"]:
            flines, _ = emit_field(name, fname, spec, layouts)
            lines.extend(flines)
        lines.append("    }")
        lines.append("")

    lines.append("}")
    return "\n".join(lines) + "\n"


def validate_params(table):
    """Guards that each parameter's wire kind and C type agree, so a param whose
    wire kind (which drives the C# type) disagrees with its ctype (which the C++
    signature pin validates against Harken.h) is a generation error rather than a
    silent C#/C mismatch. Together with the C++ signature pins this makes the C#
    signatures pinned to Harken.h transitively, for all functions."""
    for fn in table["functions"] + table.get("binding_overloads", []):
        for p in fn.get("params", []):
            wire = p["wire"]
            ctype = p["ctype"]
            is_ptr = ctype.rstrip().endswith("*")

            def bad(msg):
                raise ValueError("param drift in %s(%s): %s [wire=%s ctype=%r]"
                                 % (fn["name"], p["name"], msg, wire, ctype))

            if wire == "string":
                if ctype != "const char*":
                    bad("string wants const char*")
            elif wire == "vec3":
                if ctype != "VnVec3":
                    bad("vec3 wants VnVec3")
            elif wire == "objectid":
                if ctype != "VnObjectId" and table["api"].get("structTypedefs", {}).get(ctype) != "VnObjectId":
                    bad("objectid wants a UUID value type")
            elif wire == "polydesc":
                if ctype != "const VnEffectDesc*":
                    bad("polydesc wants const VnEffectDesc*")
            elif wire == "desc":
                if not (ctype.startswith("const ") and is_ptr and p.get("type", "") in ctype):
                    bad("desc wants const <type>*")
            elif wire == "pathdesc":
                if not (ctype.startswith("const ") and is_ptr and p.get("type", "") in ctype):
                    bad("pathdesc wants const <type>*")
            elif wire == "postactiondesc":
                if not (ctype == "const VnPostActionDesc*" and
                        p.get("type") == "VnPostActionDesc"):
                    bad("postactiondesc wants const VnPostActionDesc*")
            elif wire == "structref":
                if not (is_ptr and p.get("type", "") in ctype):
                    bad("structref wants <type>*")
            elif wire == "out":
                if not is_ptr:
                    bad("out wants a pointer ctype")
            elif wire == "outbuf":
                if ctype != "void*":
                    bad("outbuf wants void*")
            elif wire == "outu32":
                if ctype != "uint32_t*":
                    bad("outu32 wants uint32_t*")
            elif wire == "outstruct":
                if not (is_ptr and not ctype.startswith("const ")
                        and p.get("type", "") in ctype):
                    bad("outstruct wants a mutable <type>*")
            elif wire == "outrows":
                if not (is_ptr and not ctype.startswith("const ")
                        and p.get("type", "") in ctype):
                    bad("outrows wants a mutable <type>*")
            elif wire == "f32":
                if ctype != "float":
                    bad("f32 wants float")
            elif wire == "f64":
                if ctype != "double":
                    bad("f64 wants double")
            elif wire == "u32":
                if ctype not in ("uint32_t", "VnEffectType"):
                    bad("u32 wants uint32_t or VnEffectType")
            elif wire == "u64":
                if is_ptr or ctype in table["api"].get("structTypedefs", {}) or ctype in ("float", "uint32_t", "VnEffectType", "VnVec3", "VnObjectId"):
                    bad("u64 wants a 64-bit id/handle typedef")
            else:
                bad("unknown wire kind")

    types = table["types"]
    for cbname, cbdef in table.get("api", {}).get("callbacks", {}).items():
        if cbname.startswith("_"):
            continue
        return_type = cbdef.get("returnType", "void")
        if return_type not in ("void", "VnResult"):
            raise ValueError("callback %s has unsupported returnType %r"
                             % (cbname, return_type))
        for p in cbdef.get("params", []):
            kind = p.get("kind")
            ctype = p.get("ctype", "")
            is_ptr = ctype.rstrip().endswith("*")

            def cbbad(msg, _cbname=cbname, _p=p, _kind=kind, _ctype=ctype):
                raise ValueError(
                    "callback param drift in %s(%s): %s [kind=%s ctype=%r]"
                    % (_cbname, _p.get("name"), msg, _kind, _ctype))

            if kind == "ptr":
                if not is_ptr:
                    cbbad("ptr wants a pointer ctype")
            elif kind == "struct":
                if is_ptr or ctype not in types:
                    cbbad("struct wants a known non-pointer struct ctype")
            elif kind == "u64":
                if is_ptr or ctype in ("float", "uint32_t", "VnEffectType",
                                       "VnVec3"):
                    cbbad("u64 wants a 64-bit id/handle ctype")
            elif kind == "u32":
                if ctype not in ("uint32_t", "VnEffectType"):
                    cbbad("u32 wants uint32_t or VnEffectType")
            elif kind == "f32":
                if ctype != "float":
                    cbbad("f32 wants float")
            elif kind == "i32":
                if ctype not in ("int32_t", "VnResult"):
                    cbbad("i32 wants int32_t or VnResult")
            elif kind == "u8":
                if ctype != "uint8_t":
                    cbbad("u8 wants uint8_t")
            else:
                cbbad("unknown callback kind")


def cs_param(param):
    """Maps one function parameter to its C# P/Invoke form from its wire kind
    (present on every param). Blittable value types on the hot path; `in` for
    input descs (readonly ref, no copy); byte* for UTF-8 strings (no implicit
    marshaling); out/ref for pointer outputs."""
    wire = param["wire"]
    name = cs_identifier(param["name"])
    if wire == "u64":
        return "ulong %s" % name
    if wire == "objectid":
        return "VnObjectId %s" % name
    if wire == "u32":
        return "uint %s" % name
    if wire == "f32":
        return "float %s" % name
    if wire == "f64":
        return "double %s" % name
    if wire == "vec3":
        return "VnVec3 %s" % name
    if wire == "string":
        return "byte* %s" % name
    if wire == "desc":
        return "in %s %s" % (param["type"], name)
    if wire == "pathdesc":
        return "in %s %s" % (param["type"], name)
    if wire == "postactiondesc":
        return "in %s %s" % (param["type"], name)
    if wire == "polydesc":
        return "IntPtr %s" % name
    if wire == "out":
        return "out ulong %s" % name
    if wire == "outbuf":
        # Caller-provided opaque byte buffer. Keep it a raw pointer so the
        # managed caller can pin a span of capacityBytes, matching C.
        return "void* %s" % name
    if wire == "outu32":
        return "out uint %s" % name
    if wire == "outstruct":
        return "ref %s %s" % (param["type"], name)
    if wire == "outrows":
        # Caller-provided row buffer: a raw pointer keeps the projection
        # blittable and allocation-free (the SDK wraps it over a fixed or
        # pinned span), matching the C contract exactly.
        return "%s* %s" % (param["type"], name)
    if wire == "structref":
        return "ref %s %s" % (param["type"], name)
    raise ValueError("unknown wire kind for binding: %s" % wire)


def emit_native(table, policy):
    lines = [CS_HEADER]
    lines.append("using System;")
    lines.append("using System.Runtime.InteropServices;")
    lines.append("")
    lines.append("namespace %s" % NAMESPACE)
    lines.append("{")
    lines.append("    /// <summary>")
    lines.append("    /// SDK P/Invoke projection of the Harken.h C ABI. Every method")
    lines.append("    /// maps to exactly one C function; the binding owns no engine")
    lines.append("    /// semantics (thin projection). AOT/IL2CPP-safe: no runtime code")
    lines.append("    /// generation, and the native library name is a compile-time constant")
    lines.append("    /// baked per platform below.")
    lines.append("    /// </summary>")
    lines.append("    %s static unsafe class HarkenNative" % managed_access(policy, "types", "HarkenNative"))
    lines.append("    {")
    lines.append("        // Native library resolution is decided at generation/compile time,")
    lines.append("        // never at runtime: a shared library on macOS/Android/desktop, and")
    lines.append("        // __Internal on iOS where the runtime is statically linked into the")
    lines.append("        // app (iOS forbids dynamic loading).")
    lines.append("#if (UNITY_IOS || UNITY_VISIONOS || UNITY_TVOS) && !UNITY_EDITOR")
    lines.append('        public const string LibraryName = "__Internal";')
    lines.append("#else")
    lines.append('        public const string LibraryName = "HarkenCore";')
    lines.append("#endif")
    lines.append("")
    for fn in table["functions"] + table.get("binding_overloads", []):
        if not fn.get("public", True):
            continue
        name = fn["name"]
        entry_point = fn.get("entryPoint", name)
        params = fn.get("params", [])
        ps = ", ".join(cs_param(p) for p in params)
        lines.append('        [DllImport(LibraryName, EntryPoint = "%s", CallingConvention = CallingConvention.Cdecl)]' % entry_point)
        lines.append("        public static extern VnResult %s(%s);" % (name, ps))
        lines.append("")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_abi_cs(table, policy):
    layouts = gen_wire.compute_layouts(table["types"])
    lines = [CS_HEADER]
    lines.append("using System;")
    lines.append("using System.Collections.Generic;")
    lines.append("using System.Runtime.InteropServices;")
    lines.append("")
    lines.append("namespace %s" % NAMESPACE)
    lines.append("{")
    lines.append("    /// <summary>")
    lines.append("    /// Machine-checkable ABI fidelity: the expected managed size and field")
    lines.append("    /// offsets of every mirrored struct, computed from the same MSVC-x64")
    lines.append("    /// layout model the C++ side is pinned against. CheckLayout() asserts")
    lines.append("    /// Marshal.SizeOf / Marshal.OffsetOf equal these; combined with the C++")
    lines.append("    /// static_asserts (table == Harken.h), this proves the C# mirror matches")
    lines.append("    /// the C header. Pure managed reflection — needs no native library.")
    lines.append("    /// </summary>")
    lines.append("    %s static class HarkenAbi" % managed_access(policy, "types", "HarkenAbi"))
    lines.append("    {")
    lines.append("        /// <summary>Returns an empty list when the managed layout matches")
    lines.append("        /// the pinned expectations, else one string per mismatch.</summary>")
    lines.append("        public static List<string> CheckLayout()")
    lines.append("        {")
    lines.append("            var f = new List<string>();")
    for name, desc in table["types"].items():
        layout = layouts[name]
        lines.append("            Size(f, \"%s\", Marshal.SizeOf<%s>(), %d);"
                     % (name, name, layout.size))
        # Offsets keyed by the C# field name (struct arrays carry a Raw suffix).
        for fname, spec in desc["fields"]:
            _, csn = emit_field(name, fname, spec, layouts)
            off = dict(layout.fields)[fname]
            lines.append("            Off(f, \"%s\", \"%s\", Marshal.OffsetOf<%s>(\"%s\"), %d);"
                         % (name, csn, name, csn, off))
    lines.append("            return f;")
    lines.append("        }")
    lines.append("")
    lines.append("        static void Size(List<string> f, string t, int got, int want)")
    lines.append("        {")
    lines.append("            if (got != want)")
    lines.append("                f.Add($\"sizeof({t}) = {got}, expected {want}\");")
    lines.append("        }")
    lines.append("")
    lines.append("        static void Off(List<string> f, string t, string field, IntPtr got, int want)")
    lines.append("        {")
    lines.append("            if ((int)got != want)")
    lines.append("                f.Add($\"offsetof({t}.{field}) = {(int)got}, expected {want}\");")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_cpp_pin(table):
    layouts = gen_wire.compute_layouts(table["types"])
    api = table["api"]
    lines = [CPP_HEADER]
    lines.append("#ifndef HARKEN_BINDING_ABI_PIN_H")
    lines.append("#define HARKEN_BINDING_ABI_PIN_H")
    lines.append("")
    lines.append("#include <harken/Harken.h>")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("// Every enum value, result code, #define, and mirrored struct size/offset")
    lines.append("// the C# binding generates is pinned here against the real Harken.h symbol.")
    lines.append("// A mis-transcription in harken_wire_table.json (from which the binding is")
    lines.append("// generated) is therefore a compile error, never a silent binding bug.")
    lines.append("")
    lines.append("// Result codes.")
    for cname, value in api["results"]["values"].items():
        lines.append("static_assert(static_cast<int>(%s) == %d, \"binding result drift: %s\");"
                     % (cname, value, cname))
    lines.append("")
    lines.append("// Public enum values.")
    for ename, edef in api["enums"].items():
        for cname, value in edef["values"].items():
            lines.append("static_assert(static_cast<int>(%s) == %d, \"binding enum drift: %s\");"
                         % (cname, value, cname))
    lines.append("")
    lines.append("// #define constants.")
    for cname, cdef in api["defines"].items():
        if cdef["type"] == "objectid":
            value = cdef["value"]
            lines.append("static_assert(%s == VnObjectId{%dull, %dull}, \"binding define drift: %s\");" %
                         (cname, value["high"], value["low"], cname))
        elif cdef["type"] == "u64":
            lines.append("static_assert(static_cast<std::uint64_t>(%s) == %dull, \"binding define drift: %s\");"
                         % (cname, cdef["value"], cname))
        else:
            lines.append("static_assert(static_cast<std::uint64_t>(%s) == %dull, \"binding define drift: %s\");"
                         % (cname, cdef["value"], cname))
    lines.append("")
    lines.append("// Mirrored struct sizes and field offsets (the values the C# ABI test")
    lines.append("// asserts its managed layout against).")
    for name, desc in table["types"].items():
        layout = layouts[name]
        lines.append("static_assert(sizeof(%s) == %d, \"binding size drift: %s\");"
                     % (name, layout.size, name))
        for fname, off in layout.fields:
            lines.append("static_assert(offsetof(%s, %s) == %d, \"binding offset drift: %s.%s\");"
                         % (name, fname, off, name, fname))
    lines.append("")
    lines.append("// C function-signature pins for the whole API. Taking the address of each")
    lines.append("// function into a pointer of the table-declared signature makes ANY")
    lines.append("// parameter or return-type drift between the table and Harken.h a compile")
    lines.append("// error — including for functions the remote-wire dispatch never compiles")
    lines.append("// (refused-policy and opcode-less functions), which the layout pins alone")
    lines.append("// cannot catch. The C# P/Invoke signatures are generated from the same")
    lines.append("// param entries (their wire kind, guarded to agree with the ctype), so a")
    lines.append("// green build here pins the managed signatures to Harken.h transitively.")
    lines.append("// extern \"C\" so the pointer types share the engine functions' C language")
    lines.append("// linkage; static gives each an internal, unused-safe definition.")
    lines.append('extern "C" {')
    for fn in table["functions"]:
        if not fn.get("public", True):
            continue
        name = fn["name"]
        params = fn.get("params", [])
        ctypes = ", ".join(p["ctype"] for p in params) if params else "void"
        lines.append("[[maybe_unused]] static VnResult (*const binding_sig_%s)(%s) = &%s;"
                     % (name, ctypes, name))
    lines.append("}")
    lines.append("")
    lines.append("#endif // HARKEN_BINDING_ABI_PIN_H")
    return "\n".join(lines) + "\n"


def parse_args(argv):
    """Parse the command line, rejecting anything not understood.

    Membership-testing sys.argv for "--check" treated every misspelling as "no
    mode requested", so a CI step asking for --chek silently regenerated instead
    of verifying -- a gate that passes precisely when it should fail, and that
    rewrites the checked-in outputs it was meant to police.
    """
    parser = argparse.ArgumentParser(
        prog="gen_binding.py",
        description="Generate or verify the C# binding generated from "
                    "harken_wire_table.json.",
        allow_abbrev=False)
    parser.add_argument(
        "--check", action="store_true",
        help="verify the checked-in outputs match the table without "
             "rewriting them")
    return parser.parse_args(argv)


def main():
    check = parse_args(sys.argv[1:]).check
    with open(TABLE_PATH, "r", encoding="utf-8") as f:
        table = json.load(f)

    validate_params(table)
    policy = managed_policy(table)
    managed = managed_projection(table, policy)

    outputs = {
        os.path.join(CS_GEN_DIR, "HarkenTypes.g.cs"): emit_types(managed, policy),
        os.path.join(CS_GEN_DIR, "HarkenNative.g.cs"): emit_native(managed, policy),
        os.path.join(CS_GEN_DIR, "HarkenAbi.g.cs"): emit_abi_cs(managed, policy),
        os.path.join(CPP_GEN_DIR, "harken_binding_abi_pin.g.h"): emit_cpp_pin(table),
    }

    failed = False
    for path, content in outputs.items():
        if check:
            try:
                with open(path, "r", encoding="utf-8", newline="") as f:
                    existing = f.read()
            except OSError:
                existing = None
            if existing != content:
                print("MISMATCH: %s" % path)
                failed = True
            else:
                print("ok: %s" % path)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            print("wrote: %s" % path)
    if check and failed:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
