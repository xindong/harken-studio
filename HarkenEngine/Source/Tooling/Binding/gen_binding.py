#!/usr/bin/env python3
"""C# binding generator for the Harken Core public C ABI.

Reads the SAME single source of truth the remote wire layer is generated
from — HarkenEngine/Source/Tooling/Remote/wire/harken_wire_table.json — and
emits the C# P/Invoke projection plus its machine-verifiable ABI pins:

  <repo>/HarkenSDK/Unity/Harken/Runtime/Generated/HarkenTypes.g.cs
        blittable [StructLayout(Sequential)] mirrors of SDK structs,
        callback delegates, results, enums and constants.
  <repo>/HarkenSDK/Unity/Harken/Runtime/Generated/HarkenNative.g.cs
        internal [DllImport] declarations for the SDK projection,
        with the native library name baked per platform at compile time
        (HarkenCore on macOS/Android/desktop, __Internal on iOS).
  <repo>/HarkenSDK/Unity/Harken/Runtime/Generated/HarkenAbi.g.cs
        the generated ABI-fidelity check: expected managed Marshal.SizeOf /
        Marshal.OffsetOf values (computed from the same MSVC-x64 layout model
        the wire layer uses) with a CheckLayout() that returns every mismatch.
  ./generated/harken_binding_abi_pin.g.h
        C++ static_asserts comparing every enum value, result code, #define,
        and mirrored struct size/offset against the Harken.h symbols — a
        mis-transcription in the table is a compile error, never a silent
        binding bug. Compiled into harken_runtime_tests.

Managed projection and visibility come from sdk_api_surface.json, independently
of the native table's ABI and wire metadata. Monitor contracts remain native;
new SDK symbols require an explicit audience before generation succeeds.

The single-source discipline mirrors the wire layer's: header <-> binding
drift is structurally impossible because both are emitted from one table.
The generated files are checked into the repository so no consumer build
depends on Python. Regenerate after editing the table:

    py -3 HarkenEngine/Source/Tooling/Binding/gen_binding.py

Verify checked-in products match the table without rewriting them:

    py -3 HarkenEngine/Source/Tooling/Binding/gen_binding.py --check

The ABI-fidelity chain proves the C# managed layout equals the C header:
  * the C++ static_asserts prove (table values) == (Harken.h) at compile time;
  * HarkenAbi.CheckLayout() proves (C# managed layout) == (table values) at run
    time via Marshal.SizeOf / Marshal.OffsetOf;
so transitively the generated C# mirror matches Harken.h exactly.
"""

