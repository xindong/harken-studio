#!/usr/bin/env python3
"""Compile-time built-in effect registry generator.

Reads the single source of truth for the built-in insert effects —
HarkenEngine/Source/Tooling/Effects/effect_registry.json — and emits the
checked-in compile-time headers consumed by the render dispatch/effect pool and
the pack compiler/media parser:

  <repo>/HarkenEngine/Source/Runtime/render/include/harken/render/generated/
        harken_effect_registry.g.h
        A constexpr array of registry rows (one per built-in effect) carrying
        each effect's identity, pooled-state footprint, per-instance extra
        storage and capacity sources, audio-thread kernel binding, and
        logic-thread descriptor/parameter hooks, plus static_asserts pinning the
        table against the public ABI enum values and parameter-count constants.

  <repo>/HarkenEngine/Source/Runtime/media/include/harken/media/generated/
        harken_pack_effect_schema.g.h
        A dependency-light constexpr schema carrying each manifest spelling,
        public effect type, descriptor vintage, parameter count, and authored
        parameter ranges. Packc and the shipping media parser consume this
        header without depending on Python or the render registry.

Following the binding-pin precedent (gen_binding.py), the generator lives with
its source table under Tooling/ but writes into the tree of its consumer. The
render tree was chosen over a Tooling/ output location because the registry is
consumed by the runtime library itself (BuiltinEffects.cpp, EffectPool.h) and
transitively by every target that pulls in Engine.h; render/include is already
on all of their include paths, so no build wiring changes to consume it.

Both paths first cross-check the manifest against the PUBLIC effect ids parsed
from Harken.h (the VnEffectType enum block): a public id with no manifest row, a
manifest row with no public id, a value mismatch, or a row-order mismatch fails
loudly with the exact ids. This is the machine-checked completeness the design
requires — the emitted static_asserts alone would compile even if a released
public id had no row.

The generated header is checked into the repository so no consumer build depends
on Python. Regenerate after editing the table:

    py -3 HarkenEngine/Source/Tooling/Effects/gen_effect_registry.py

Verify both checked-in products match the table AND the public ids without
rewriting them (also wired as the ctest effect_registry_manifest_check):

    py -3 HarkenEngine/Source/Tooling/Effects/gen_effect_registry.py --check
"""

