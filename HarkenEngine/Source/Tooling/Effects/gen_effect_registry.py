def fmt_float(v):
    """Format a JSON number as a C++ float literal (always dotted, f-suffixed)."""
    s = repr(float(v))
    if "e" in s or "E" in s:
        return s + "f"  # exponent form is a valid float literal as-is
    if "." not in s:
        s += ".0"
    return s + "f"


def mask_expr(values, mapping):
    return " | ".join(mapping[value] for value in values) if values else "0u"


def param_meta_array(effect):
    return "k" + effect["hookPrefix"] + "ParamMeta"


def param_clamp_min(effect, param):
    """A numeric clampMin becomes a float literal; the token "strictlyPositive"
    becomes the smallest-positive-float sentinel, which resolves at reduction time
    to std::numeric_limits<float>::denorm_min() so the store's lower clamp matches the
    released validator's open "value > 0" rule exactly (never a tighter floor)."""
    cm = param["clampMin"]
    if isinstance(cm, str):
        if cm not in CLAMP_MIN_TOKENS:
            raise SystemExit(
                "%s.%s: unknown clampMin token %r" %
                (effect["name"], param["name"], cm))
        return CLAMP_MIN_TOKENS[cm]
    return fmt_float(cm)


def param_clamp_max(effect, param):
    """A numeric clampMax becomes a float literal. "nyquist" and
    "strictlyBelowOne" become distinct runtime-resolved sentinels."""
    cm = param["clampMax"]
    if isinstance(cm, str):
        if cm not in CLAMP_MAX_TOKENS:
            raise SystemExit(
                "%s.%s: unknown clampMax token %r" %
                (effect["name"], param["name"], cm))
        return CLAMP_MAX_TOKENS[cm]
    return fmt_float(cm)


def pack_authored_min(param):
    """Return (value, present, inclusive) for the sample-rate-independent
    authored lower bound."""
    value = param["clampMin"]
    if value == "strictlyPositive":
        return (0.0, True, False)
    if isinstance(value, str):
        raise SystemExit("unknown authored clampMin token %r" % value)
    return (value, True, True)


def pack_authored_max(param):
    """Return (value, present, inclusive) for the authored upper bound.
    Nyquist is deliberately absent: packc has no target sample rate, and the
    runtime registry validator remains authoritative for that staging check."""
    value = param["clampMax"]
    if value == "nyquist":
        return (0.0, False, False)
    if value == "strictlyBelowOne":
        return (1.0, True, False)
    if isinstance(value, str):
        raise SystemExit("unknown authored clampMax token %r" % value)
    return (value, True, True)


def finite_float32(effect, param, field):
    """Validate a manifest number and return its IEEE-754 binary32 value."""
    value = param[field]
    label = "%s.%s" % (effect["name"], param["name"])
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise SystemExit(
            "%s: %s must be numeric (bool and non-numeric values are invalid)" %
            (label, field))
    try:
        value64 = float(value)
    except (OverflowError, ValueError):
        raise SystemExit(
            "%s: %s must be representable as a finite float32" %
            (label, field))
    if not math.isfinite(value64):
        raise SystemExit(
            "%s: %s must be finite before float32 normalization" %
            (label, field))
    try:
        value32 = struct.unpack("<f", struct.pack("<f", value64))[0]
    except (OverflowError, struct.error):
        raise SystemExit(
            "%s: %s must be representable as a finite float32" %
            (label, field))
    if not math.isfinite(value32):
        raise SystemExit(
            "%s: %s must normalize to a finite float32" % (label, field))
    return value32


def clamp_sentinel_float32_values():
    """Return the exact binary32 values reserved by generated C++ sentinels."""
    return {
        name: struct.unpack(
            "<f", struct.pack("<f", float(literal[:-1])))[0]
        for name, literal in CLAMP_SENTINEL_LITERALS.items()
    }


def validate_numeric_clamp(effect, param, field, sentinels):
    value = param[field]
    if isinstance(value, str):
        if field == "clampMin":
            param_clamp_min(effect, param)
        else:
            param_clamp_max(effect, param)
        return
    value32 = finite_float32(effect, param, field)
    for sentinel_name, sentinel32 in sentinels.items():
        if value32 == sentinel32:
            raise SystemExit(
                "%s.%s: %s numeric value collides with reserved %s sentinel "
                "after float32 normalization" %
                (effect["name"], param["name"], field, sentinel_name))


def validate_params(effects):
    """Reject an unknown unit or combine token before emitting, so a typo in the
    manifest fails the generator rather than emitting an undeclared enumerator."""
    sentinels = clamp_sentinel_float32_values()
    if len(set(sentinels.values())) != len(sentinels):
        raise SystemExit("effect parameter clamp sentinels must be unique")
    for e in effects:
        vintage = e.get("descriptorVintage")
        if not isinstance(vintage, int) or vintage <= 0:
            raise SystemExit(
                "effect %s: descriptorVintage must be a positive integer" %
                e["name"])
        scopes = e.get("hostScopes")
        if (not isinstance(scopes, list) or not scopes or
                len(scopes) != len(set(scopes))):
            raise SystemExit(
                "effect %s: hostScopes must be a non-empty unique list" %
                e["name"])
        for scope in scopes:
            if scope not in HOST_SCOPES:
                raise SystemExit(
                    "effect %s: unknown host scope %r" %
                    (e["name"], scope))
        dynamic = e.get("dynamic")
        if not isinstance(dynamic, dict):
            raise SystemExit(
                "effect %s: dynamic metadata object is required" % e["name"])
        dynamic_lists = [
            ("acceptedSignalForms", DYNAMIC_SIGNAL_FORMS),
            ("allowedSourceKinds", DYNAMIC_SOURCE_KINDS),
            ("allowedBusTaps", DYNAMIC_BUS_TAPS),
            ("allowedVoiceTaps", DYNAMIC_VOICE_TAPS),
            ("flags", DYNAMIC_FLAGS),
        ]
        for field, allowed in dynamic_lists:
            values = dynamic.get(field)
            if (not isinstance(values, list) or
                    len(values) != len(set(values))):
                raise SystemExit(
                    "effect %s: dynamic.%s must be a unique list" %
                    (e["name"], field))
            for value in values:
                if value not in allowed:
                    raise SystemExit(
                        "effect %s: dynamic.%s has unknown value %r" %
                        (e["name"], field, value))
        for field in ("maxRawRoutes", "rawBusLatencyBlocks",
                      "rawVoiceLatencyBlocks", "rawRouteCombine",
                      "rawChannelReduction"):
            if not isinstance(dynamic.get(field), int) or dynamic[field] < 0:
                raise SystemExit(
                    "effect %s: dynamic.%s must be a non-negative integer" %
                    (e["name"], field))
        for field in ("rawRouteLevelMinDb", "rawRouteLevelMaxDb",
                      "rawRouteLevelDefaultDb"):
            value = dynamic.get(field)
            if (isinstance(value, bool) or
                    not isinstance(value, (int, float)) or
                    not math.isfinite(float(value))):
                raise SystemExit(
                    "effect %s: dynamic.%s must be finite numeric" %
                    (e["name"], field))
        for p in e.get("params", []):
            if p["unit"] not in PARAM_UNITS:
                raise SystemExit(
                    "param %s.%s: unknown unit %r" %
                    (e["name"], p["name"], p["unit"]))
            if p["combine"] not in PARAM_COMBINES:
                raise SystemExit(
                    "param %s.%s: unknown combine %r" %
                    (e["name"], p["name"], p["combine"]))
            if not isinstance(p.get("dynamicControlSafe"), bool):
                raise SystemExit(
                    "param %s.%s: dynamicControlSafe must be boolean" %
                    (e["name"], p["name"]))
            neutral = finite_float32(e, p, "neutral")
            expected_neutral = 1.0 if p["combine"] == "Multiply" else 0.0
            if neutral != expected_neutral:
                raise SystemExit(
                    "%s.%s: neutral must equal the %s combine identity %.1f "
                    "after float32 normalization (got %r)" %
                    (e["name"], p["name"], p["combine"],
                     expected_neutral, neutral))
            validate_numeric_clamp(e, p, "clampMin", sentinels)
            validate_numeric_clamp(e, p, "clampMax", sentinels)


def validate_params_contract_self_check():
    """Prove fail-closed numeric contracts without reading or writing files."""
    base_param = {
        "unit": "Linear",
        "combine": "AddDb",
        "neutral": 0.0,
        "clampMin": 0.0,
        "clampMax": 1.0,
        "transition": False,
        "dynamicControlSafe": False,
    }
    cases = [
        ("sentinelCollision",
         {"clampMin": -1.0},
         "collides with reserved nyquist sentinel"),
        ("multiplyWrongNeutral",
         {"combine": "Multiply", "neutral": 0.0},
         "neutral must equal the Multiply combine identity"),
        ("nanNeutral",
         {"neutral": float("nan")},
         "neutral must be finite before float32 normalization"),
        ("infiniteClamp",
         {"clampMax": float("inf")},
         "clampMax must be finite before float32 normalization"),
        ("booleanClamp",
         {"clampMin": True},
         "clampMin must be numeric"),
        ("nonNumericNeutral",
         {"neutral": []},
         "neutral must be numeric"),
    ]
    for param_name, overrides, expected_reason in cases:
        param = dict(base_param)
        param.update(overrides)
        param["name"] = param_name
        effect = {
            "name": "contractSelfCheck",
            "descriptorVintage": 1,
            "hostScopes": ["voice"],
            "dynamic": {
                "acceptedSignalForms": ["control"],
                "allowedSourceKinds": ["variable"],
                "allowedBusTaps": [],
                "allowedVoiceTaps": [],
                "maxRawRoutes": 0,
                "rawBusLatencyBlocks": 0,
                "rawVoiceLatencyBlocks": 0,
                "flags": ["controlUsesBinding", "packControl"],
                "rawRouteLevelMinDb": 0.0,
                "rawRouteLevelMaxDb": 0.0,
                "rawRouteLevelDefaultDb": 0.0,
                "rawRouteCombine": 0,
                "rawChannelReduction": 0,
            },
            "params": [param],
        }
        try:
            validate_params([effect])
        except SystemExit as exc:
            if expected_reason not in str(exc):
                raise SystemExit(
                    "generator contract self-check %s failed with unexpected "
                    "reason: %s" % (param_name, exc))
        else:
            raise SystemExit(
                "generator contract self-check %s failed: validate_params "
                "accepted invalid metadata" % param_name)


def emit(table):
    effects = table["effects"]
    n = len(effects)
    L = [HEADER]
    L.append("#ifndef HARKEN_RENDER_GENERATED_EFFECT_REGISTRY_G_H")
    L.append("#define HARKEN_RENDER_GENERATED_EFFECT_REGISTRY_G_H")
    L.append("")
    L.append("#include <harken/Harken.h>")
    L.append("")
    L.append('#include "harken/core/EngineConfig.h"')
    L.append('#include "harken/render/BuiltinEffects.h"')
    L.append('#include "harken/render/InsertEffect.h"')
    L.append("")
    L.append("#include <cstddef>")
    L.append("#include <cstdint>")
    L.append("")
    L.append("namespace harken {")
    L.append("")
    L.append("// Combination domain for a bound effect parameter. AddDb: contributions sum in")
    L.append("// dB on the base. Multiply: commutative product on the base (neutral 1).")
    L.append("// AddLogHz / AddLogQ / AddLogTime: base scaled by 2^(sum of")
    L.append("// contributions), an octave-linear shift. None: binding is unsupported,")
    L.append("// so attaching one is refused (never implicit last-writer-wins).")
    L.append("enum class EffectParamCombine : std::uint32_t {")
    L.append("    AddDb,")
    L.append("    Multiply,")
    L.append("    AddLogHz,")
    L.append("    AddLogQ,")
    L.append("    None,")
    L.append("    AddLogTime,")
    L.append("};")
    L.append("")
    L.append("// Unit of a parameter's authored value (tooling / observability).")
    L.append("enum class EffectParamUnit : std::uint32_t {")
    L.append("    Db,")
    L.append("    Linear,")
    L.append("    Hz,")
    L.append("    Q,")
    L.append("    Ms,")
    L.append("    Ratio,")
    L.append("};")
    L.append("")
    L.append("// Sentinel clampMax: the resolved value is bounded STRICTLY BELOW the Nyquist")
    L.append("// frequency (0.5 * sampleRate), resolved at reduction time (not a fixed literal),")
    L.append("// so a composed frequency always satisfies the released validator's freq <")
    L.append("// nyquist rule when it reaches the audio thread.")
    L.append("inline constexpr float kEffectParamClampNyquist = %s;" %
             CLAMP_SENTINEL_LITERALS["nyquist"])
    L.append("")
    L.append("// Sentinel clampMin: the resolved value's lower bound is the smallest positive")
    L.append("// float (std::numeric_limits<float>::denorm_min()), resolved at reduction time. It")
    L.append("// expresses the released validator's open \"value > 0\" rule for frequency and Q")
    L.append("// EXACTLY -- a numeric floor here would be tighter than the validator and would")
    L.append("// suppress a valid low composed value. Chosen far below any real parameter floor")
    L.append("// so it can never collide with an authored numeric clampMin.")
    L.append("inline constexpr float kEffectParamClampStrictlyPositive = %s;" %
             CLAMP_SENTINEL_LITERALS["strictlyPositive"])
    L.append("")
    L.append("// Sentinel clampMax: the resolved value's upper bound is the largest float")
    L.append("// strictly below 1.0f (std::nextafter(1.0f, 0.0f)). It expresses an open")
    L.append("// \"value < 1\" validator bound without tightening the accepted domain.")
    L.append("inline constexpr float kEffectParamClampStrictlyBelowOne = %s;" %
             CLAMP_SENTINEL_LITERALS["strictlyBelowOne"])
    L.append("")
    L.append("static_assert(kEffectParamClampNyquist !=")
    L.append("                  kEffectParamClampStrictlyPositive &&")
    L.append("              kEffectParamClampNyquist !=")
    L.append("                  kEffectParamClampStrictlyBelowOne &&")
    L.append("              kEffectParamClampStrictlyPositive !=")
    L.append("                  kEffectParamClampStrictlyBelowOne,")
    L.append("              \"effect parameter clamp sentinels must be unique\");")
    L.append("")
    L.append("// Metadata authority for one effect parameter (see effect_registry.json). The")
    L.append("// binding resolver reads combine/neutral/clamp to compose a parameter's")
    L.append("// contributions on its base and clamp the result before it reaches the audio")
    L.append("// thread; a parameter's authored direct value is the base.")
    L.append("struct EffectParamMeta {")
    L.append("    const char* name;")
    L.append("    EffectParamUnit unit;")
    L.append("    EffectParamCombine combine;")
    L.append("    float neutral; // binding-combine identity, not an authored default")
    L.append("    float clampMin; // strictly-positive sentinel => denorm_min()")
    L.append("    float clampMax; // Nyquist/open-one sentinel => concrete bound")
    L.append("    bool supportsTransition;")
    L.append("    bool dynamicControlSafe;")
    L.append("};")
    L.append("")
    L.append("// One compile-time registry row per built-in insert effect. The row carries")
    L.append("// the effect's identity, its pooled-state footprint, the per-instance extra")
    L.append("// storage and capacity sources the pool sizes from at Init, the audio-thread")
    L.append("// kernel binding, and the logic-thread descriptor/parameter hooks the dispatch")
    L.append("// uses. Row order equals effect-type order.")
    L.append("struct EffectRegistryRow {")
    L.append("    std::uint32_t effectType;")
    L.append("    std::uint32_t paramCount;")
    L.append("    std::uint32_t descriptorSize;")
    L.append("    std::uint32_t descriptorVintage;")
    L.append("    std::uint32_t hostScopeMask;")
    L.append("    std::uint32_t stateSize;")
    L.append("    std::uint32_t stateAlign;")
    L.append("    std::uint32_t dynamicSignalFormsMask;")
    L.append("    std::uint32_t dynamicSourceKindsMask;")
    L.append("    std::uint32_t dynamicBusTapsMask;")
    L.append("    std::uint32_t dynamicVoiceTapsMask;")
    L.append("    std::uint32_t dynamicMaxRawRoutes;")
    L.append("    std::uint32_t dynamicRawBusLatencyBlocks;")
    L.append("    std::uint32_t dynamicRawVoiceLatencyBlocks;")
    L.append("    std::uint32_t dynamicFlags;")
    L.append("    float dynamicRawRouteLevelMinDb;")
    L.append("    float dynamicRawRouteLevelMaxDb;")
    L.append("    float dynamicRawRouteLevelDefaultDb;")
    L.append("    std::uint32_t dynamicRawRouteCombine;")
    L.append("    std::uint32_t dynamicRawChannelReduction;")
    L.append("    // Per-instance extra storage the pool preallocates at Init, in frames per")
    L.append("    // channel across kMaxChannels (the feedback-delay line); 0 when the whole")
    L.append("    // instance state fits in the state struct.")
    L.append("    std::uint32_t (*extraFramesPerChannel)(const EngineConfig& config);")
    L.append("    // Per-type instance capacity, read from the EngineConfig field named by")
    L.append("    // capacitySource.")
    L.append("    std::uint32_t (*capacity)(const EngineConfig& config);")
    L.append("    // Placement-constructs one instance in pool storage and wires its extra")
    L.append("    // storage and sample rate (logic side, Init only).")
    L.append("    void (*initInstance)(void* state, float* extra,")
    L.append("                         std::uint32_t extraFramesPerChannel,")
    L.append("                         std::uint32_t sampleRate);")
    L.append("    // Audio-thread kernel binding (assembled into an InsertEffect by")
    L.append("    // BuildEffect).")
    L.append("    void (*process)(void* state, float* const* channels,")
    L.append("                    std::uint32_t channelCount, std::uint32_t offset,")
    L.append("                    std::uint32_t frames);")
    L.append("    std::uint32_t (*tailFrames)(const void* state);")
    L.append("    void (*setParam)(void* state, std::uint32_t paramIndex, float value);")
    L.append("    void (*reset)(void* state);")
    L.append("    // Logic-thread descriptor/parameter hooks.")
    L.append("    VnResult (*validateDesc)(const void* desc, std::uint32_t sampleRate);")
    L.append("    VnResult (*validateParam)(std::uint32_t paramIndex, float value,")
    L.append("                              std::uint32_t sampleRate);")
    L.append("    std::uint32_t (*paramsFromDesc)(const void* desc, float* out);")
    L.append("    // Observability label and the EngineConfig capacity field name (the")
    L.append("    // registry completeness proof reads these).")
    L.append("    const char* label;")
    L.append("    const char* capacitySource;")
    L.append("    // The effect's parameter metadata authority, paramCount entries in private")
    L.append("    // parameter-index order (entry i describes parameter index i).")
    L.append("    const EffectParamMeta* params;")
    L.append("};")
    L.append("")
    L.append("// Per-effect hooks, defined in BuiltinEffects.cpp. Declared here so the")
    L.append("// registry rows below can bind their addresses; a definition whose signature")
    L.append("// disagrees with the declaration is a compile error.")
    for e in effects:
        for _, suffix, sig in HOOKS:
            L.append(sig % hook_name(e, suffix) + ";")
    L.append("")
    L.append("// Per-effect parameter metadata, one entry per private parameter index in")
    L.append("// index order. Each row of kEffectRegistry points at its effect's array.")
    for e in effects:
        L.append("inline constexpr EffectParamMeta %s[] = {" % param_meta_array(e))
        for p in e["params"]:
            L.append("    {\"%s\", EffectParamUnit::%s, EffectParamCombine::%s, "
                     "%s, %s, %s, %s, %s},"
                     % (p["name"], p["unit"], p["combine"], fmt_float(p["neutral"]),
                        param_clamp_min(e, p), param_clamp_max(e, p),
                        "true" if p["transition"] else "false",
                        "true" if p["dynamicControlSafe"] else "false"))
        L.append("};")
    L.append("")
    L.append("inline constexpr std::uint32_t kEffectRegistryRowCount = %d;" % n)
    L.append("")
    L.append("inline constexpr EffectRegistryRow"
             " kEffectRegistry[kEffectRegistryRowCount] = {")
    for e in effects:
        st = e["stateType"]
        L.append("    {")
        L.append("        %s," % e["effectEnum"])
        L.append("        %s," % e["paramCountConst"])
        L.append("        static_cast<std::uint32_t>(sizeof(%s))," %
                 e["descType"])
        L.append("        %du," % e["descriptorVintage"])
        L.append("        %s," %
                 " | ".join(HOST_SCOPES[s] for s in e["hostScopes"]))
        L.append("        static_cast<std::uint32_t>(sizeof(%s))," % st)
        L.append("        static_cast<std::uint32_t>(alignof(%s))," % st)
        dynamic = e["dynamic"]
        L.append("        %s," % mask_expr(
            dynamic["acceptedSignalForms"], DYNAMIC_SIGNAL_FORMS))
        L.append("        %s," % mask_expr(
            dynamic["allowedSourceKinds"], DYNAMIC_SOURCE_KINDS))
        L.append("        %s," % mask_expr(
            dynamic["allowedBusTaps"], DYNAMIC_BUS_TAPS))
        L.append("        %s," % mask_expr(
            dynamic["allowedVoiceTaps"], DYNAMIC_VOICE_TAPS))
        L.append("        %du," % dynamic["maxRawRoutes"])
        L.append("        %du," % dynamic["rawBusLatencyBlocks"])
        L.append("        %du," % dynamic["rawVoiceLatencyBlocks"])
        L.append("        %s," % mask_expr(dynamic["flags"], DYNAMIC_FLAGS))
        L.append("        %s," % fmt_float(dynamic["rawRouteLevelMinDb"]))
        L.append("        %s," % fmt_float(dynamic["rawRouteLevelMaxDb"]))
        L.append("        %s," % fmt_float(dynamic["rawRouteLevelDefaultDb"]))
        L.append("        %du," % dynamic["rawRouteCombine"])
        L.append("        %du," % dynamic["rawChannelReduction"])
        L.append("        &%s," % hook_name(e, "ExtraFramesPerChannel"))
        L.append("        &%s," % hook_name(e, "CapacitySource"))
        L.append("        &%s," % hook_name(e, "InitInstance"))
        L.append("        &%s," % hook_name(e, "Process"))
        L.append("        &%s," % hook_name(e, "Tail"))
        L.append("        &%s," % hook_name(e, "SetParam"))
        L.append("        &%s," % hook_name(e, "Reset"))
        L.append("        &%s," % hook_name(e, "ValidateDesc"))
        L.append("        &%s," % hook_name(e, "ValidateParam"))
        L.append("        &%s," % hook_name(e, "ParamsFromDesc"))
        L.append('        "%s",' % e["label"])
        L.append('        "%s",' % e["capacitySource"])
        L.append("        %s," % param_meta_array(e))
        L.append("    },")
    L.append("};")
    L.append("")
    L.append("// Resolves an effect-type id to its registry row, or nullptr for an unknown")
    L.append("// type (the caller treats that as an empty/refused effect, unchanged from the")
    L.append("// hand-written dispatch's default cases).")
    L.append("inline const EffectRegistryRow* FindEffectRow(std::uint32_t type) {")
    L.append("    for (std::uint32_t i = 0; i < kEffectRegistryRowCount; ++i) {")
    L.append("        if (kEffectRegistry[i].effectType == type) {")
    L.append("            return &kEffectRegistry[i];")
    L.append("        }")
    L.append("    }")
    L.append("    return nullptr;")
    L.append("}")
    L.append("")
    L.append("// Resolves (effect type, parameter index) to its parameter metadata, or nullptr")
    L.append("// when the type is unknown or the index is outside the type's parameter space.")
    L.append("inline const EffectParamMeta* FindEffectParamMeta(std::uint32_t type,")
    L.append("                                                  std::uint32_t paramIndex) {")
    L.append("    const EffectRegistryRow* row = FindEffectRow(type);")
    L.append("    if (row == nullptr || paramIndex >= row->paramCount) {")
    L.append("        return nullptr;")
    L.append("    }")
    L.append("    return &row->params[paramIndex];")
    L.append("}")
    L.append("")
    L.append("// Consistency pins: the row count must fit the fixed VnSnapshot per-type")
    L.append("// stats table, the table's effect-type value must equal the public ABI enum,")
    L.append("// the rows must be in effect-type order, each row's parameter count must equal")
    L.append("// the public per-type constant, and every pooled state type must be no more")
    L.append("// aligned than the pool's storage guarantees. A mismatch is a compile error,")
    L.append("// never a silent registry bug. (Completeness against the public effect-id set")
    L.append("// is cross-checked by the generator against Harken.h.)")
    L.append('static_assert(kEffectRegistryRowCount == %d,' % n)
    L.append('              "effect registry row count drift");')
    L.append("static_assert(kEffectRegistryRowCount <= VN_MAX_EFFECT_TYPE_STATS,")
    L.append('              "the registry must fit the fixed VnSnapshot per-type '
             'stats table (VN_MAX_EFFECT_TYPE_STATS rows)");')
    for i, e in enumerate(effects):
        L.append("static_assert(%s == %d,"
                 % (e["effectEnum"], e["effectValue"]))
        L.append('              "effect-type ABI value drift: %s");' % e["name"])
        L.append("static_assert(kEffectRegistry[%d].effectType == %d,"
                 % (i, e["effectValue"]))
        L.append('              "effect registry row order must match effect-type'
                 ' order: %s");' % e["name"])
        L.append("static_assert(kEffectRegistry[%d].paramCount == %s,"
                 % (i, e["paramCountConst"]))
        L.append('              "effect registry param-count drift: %s");'
                 % e["name"])
        L.append("static_assert(alignof(%s) <= alignof(std::max_align_t),"
                 % e["stateType"])
        L.append('              "pooled state over-aligned for pool storage: %s");'
                 % e["name"])
        L.append("static_assert(sizeof(%s) / sizeof(EffectParamMeta) == %s,"
                 % (param_meta_array(e), e["paramCountConst"]))
        L.append('              "effect parameter metadata count must equal the '
                 'parameter-count constant: %s");' % e["name"])
    L.append("")
    L.append("} // namespace harken")
    L.append("")
    L.append("#endif // HARKEN_RENDER_GENERATED_EFFECT_REGISTRY_G_H")
    return "\n".join(L) + "\n"


def emit_pack_schema(table):
    """Emit the dependency-light Pack authoring/wire schema."""
    effects = table["effects"]
    L = [HEADER.rstrip(), ""]
    L.append("#ifndef HARKEN_MEDIA_GENERATED_PACK_EFFECT_SCHEMA_G_H")
    L.append("#define HARKEN_MEDIA_GENERATED_PACK_EFFECT_SCHEMA_G_H")
    L.append("")
    L.append("#include <harken/Harken.h>")
    L.append("")
    L.append("#include <cmath>")
    L.append("#include <cstdint>")
    L.append("#include <cstring>")
    L.append("")
    L.append("namespace harken {")
    L.append("")
    L.append("struct PackEffectAuthoredRange {")
    L.append("    float minimum;")
    L.append("    float maximum;")
    L.append("    bool hasMinimum;")
    L.append("    bool hasMaximum;")
    L.append("    bool minimumInclusive;")
    L.append("    bool maximumInclusive;")
    L.append("};")
    L.append("")
    L.append("struct PackEffectSchemaRow {")
    L.append("    const char* manifestName;")
    L.append("    std::uint32_t effectType;")
    L.append("    std::uint32_t descriptorVintage;")
    L.append("    std::uint32_t paramCount;")
    L.append("    const PackEffectAuthoredRange* authoredRanges;")
    L.append("};")
    L.append("")
    for e in effects:
        array_name = "kPack%sAuthoredRanges" % e["hookPrefix"]
        L.append("inline constexpr PackEffectAuthoredRange %s[] = {" %
                 array_name)
        for p in e["params"]:
            minimum, has_minimum, minimum_inclusive = pack_authored_min(p)
            maximum, has_maximum, maximum_inclusive = pack_authored_max(p)
            L.append("    {%s, %s, %s, %s, %s, %s}," %
                     (fmt_float(minimum), fmt_float(maximum),
                      "true" if has_minimum else "false",
                      "true" if has_maximum else "false",
                      "true" if minimum_inclusive else "false",
                      "true" if maximum_inclusive else "false"))
        L.append("};")
    L.append("")
    L.append("inline constexpr std::uint32_t kPackEffectSchemaRowCount = %du;" %
             len(effects))
    display_names = ", ".join('\\"%s\\"' % e["name"]
                              for e in effects)
    L.append('inline constexpr const char kPackEffectManifestNameList[] = "%s";' %
             display_names)
    L.append("inline constexpr PackEffectSchemaRow")
    L.append("    kPackEffectSchema[kPackEffectSchemaRowCount] = {")
    for e in effects:
        L.append('        {"%s", %s, %du, %du, kPack%sAuthoredRanges},' %
                 (e["name"], e["effectEnum"], e["descriptorVintage"],
                  len(e["params"]), e["hookPrefix"]))
    L.append("};")
    L.append("")
    L.append("inline const PackEffectSchemaRow*")
    L.append("FindPackEffectSchemaByType(std::uint32_t type) {")
    L.append("    for (std::uint32_t i = 0; i < kPackEffectSchemaRowCount; ++i) {")
    L.append("        if (kPackEffectSchema[i].effectType == type) {")
    L.append("            return &kPackEffectSchema[i];")
    L.append("        }")
    L.append("    }")
    L.append("    return nullptr;")
    L.append("}")
    L.append("")
    L.append("inline const PackEffectSchemaRow*")
    L.append("FindPackEffectSchemaByManifestName(const char* name) {")
    L.append("    if (name == nullptr) {")
    L.append("        return nullptr;")
    L.append("    }")
    L.append("    for (std::uint32_t i = 0; i < kPackEffectSchemaRowCount; ++i) {")
    L.append("        if (std::strcmp(kPackEffectSchema[i].manifestName, name) == 0) {")
    L.append("            return &kPackEffectSchema[i];")
    L.append("        }")
    L.append("    }")
    L.append("    return nullptr;")
    L.append("}")
    L.append("")
    L.append("inline bool PackEffectParamInAuthoredRange(")
    L.append("    std::uint32_t type, std::uint32_t index, float value) {")
    L.append("    if (!std::isfinite(value)) {")
    L.append("        return false;")
    L.append("    }")
    L.append("    const PackEffectSchemaRow* row = FindPackEffectSchemaByType(type);")
    L.append("    if (row == nullptr || index >= row->paramCount) {")
    L.append("        return false;")
    L.append("    }")
    L.append("    const PackEffectAuthoredRange& range = row->authoredRanges[index];")
    L.append("    if (range.hasMinimum &&")
    L.append("        (value < range.minimum ||")
    L.append("         (!range.minimumInclusive && value == range.minimum))) {")
    L.append("        return false;")
    L.append("    }")
    L.append("    if (range.hasMaximum &&")
    L.append("        (value > range.maximum ||")
    L.append("         (!range.maximumInclusive && value == range.maximum))) {")
    L.append("        return false;")
    L.append("    }")
    L.append("    return true;")
    L.append("}")
    L.append("")
    for i, e in enumerate(effects):
        L.append("static_assert(%s == %d," %
                 (e["effectEnum"], e["effectValue"]))
        L.append('              "effect-type ABI value drift: %s");' %
                 e["name"])
        L.append("static_assert(kPackEffectSchema[%d].paramCount == %du," %
                 (i, len(e["params"])))
        L.append('              "Pack effect parameter-count drift: %s");' %
                 e["name"])
    L.append("")
    L.append("} // namespace harken")
    L.append("")
    L.append("#endif // HARKEN_MEDIA_GENERATED_PACK_EFFECT_SCHEMA_G_H")
    return "\n".join(L) + "\n"


def parse_args(argv):
    """Parse the command line, rejecting anything not understood.

    Membership-testing sys.argv for "--check" treated every misspelling as "no
    mode requested", so a CI step asking for --chek silently regenerated instead
    of verifying -- a gate that passes precisely when it should fail, and that
    rewrites the checked-in outputs it was meant to police.
    """
    parser = argparse.ArgumentParser(
        prog="gen_effect_registry.py",
        description="Generate or verify the built-in effect registry generated "
                    "from effect_registry.json.",
        allow_abbrev=False)
    parser.add_argument(
        "--check", action="store_true",
        help="verify the checked-in outputs match the table without "
             "rewriting them")
    return parser.parse_args(argv)


def main():
    check = parse_args(sys.argv[1:]).check
    # Both generation modes prove the validator's fail-closed contract before
    # touching the manifest or generated output.
    validate_params_contract_self_check()
    with open(TABLE_PATH, "r", encoding="utf-8") as f:
        table = json.load(f)
    # Completeness against the public effect ids runs on both paths: a manifest
    # that has drifted from Harken.h must fail the --check ctest and must refuse
    # to (re)generate a header that would silently mis-cover the released types.
    check_completeness(table["effects"], HARKEN_H)
    validate_params(table["effects"])
    outputs = [
        (OUT_PATH, emit(table)),
        (PACK_SCHEMA_OUT_PATH, emit_pack_schema(table)),
    ]
    if check:
        mismatched = False
        for path, content in outputs:
            try:
                with open(path, "r", encoding="utf-8", newline="") as f:
                    existing = f.read()
            except OSError:
                existing = None
            if existing != content:
                print("MISMATCH: %s" % path)
                mismatched = True
            else:
                print("ok: %s" % path)
        return 1 if mismatched else 0
    for path, content in outputs:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote: %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
