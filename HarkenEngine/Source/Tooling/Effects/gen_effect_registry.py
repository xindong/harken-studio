def parse_public_effect_ids(header_path):
    """Extract the public built-in effect ids from Harken.h as the source of
    truth for completeness. Anchors on the `typedef uint32_t VnEffectType;`
    declaration and reads the enum block immediately following it, so unrelated
    VN_ constants (and the VN_EFFECT_* mentions in nearby doc comments) are not
    swept in. Fails loudly if the anchor or the enum block is missing, or if the
    block carries an effect entry without an explicit ABI value, rather than
    silently matching nothing. Returns [(name, value), ...] in source order."""
    with open(header_path, "r", encoding="utf-8") as f:
        text = f.read()

    anchor = "typedef uint32_t VnEffectType;"
    ai = text.find(anchor)
    if ai < 0:
        raise SystemExit(
            "effect-id parse: anchor %r not found in %s" % (anchor, header_path))
    ei = text.find("enum", ai)
    ob = text.find("{", ei) if ei >= 0 else -1
    cb = text.find("}", ob) if ob >= 0 else -1
    if ei < 0 or ob < 0 or cb < 0:
        raise SystemExit(
            "effect-id parse: no enum block after %r in %s" % (anchor,
                                                               header_path))
    body = text[ob + 1:cb]

    # Every effect id token in the block, and every id carrying an explicit
    # value. Effect ids are ABI-fixed and always written with an explicit value;
    # if the two counts disagree an entry relies on implicit enum increment,
    # which this cross-check does not model, so fail rather than guess.
    idents = re.findall(r"\bVN_EFFECT_[A-Z0-9_]+\b", body)
    pairs = re.findall(r"\b(VN_EFFECT_[A-Z0-9_]+)\s*=\s*(-?\d+)", body)
    if len(idents) != len(pairs):
        raise SystemExit(
            "effect-id parse: %d effect ids but %d carry explicit values in the "
            "VnEffectType enum; every effect id must have an explicit ABI value "
            "(%r)" % (len(idents), len(pairs), idents))
    return [(name, int(value)) for name, value in pairs]


def check_completeness(effects, header_path):
    """Cross-check the manifest against the public effect ids in Harken.h. The
    generated static_asserts alone cannot catch a public id that gains no
    manifest row (the header would compile and silently refuse a released type
    at runtime), so this runs before every generate and every --check. Reports
    all discrepancies with exact ids and fails the run."""
    public = parse_public_effect_ids(header_path)
    public_by_name = dict(public)
    manifest = [(e["effectEnum"], e["effectValue"]) for e in effects]
    manifest_by_name = dict(manifest)

    errors = []
    for name, value in public:
        if name not in manifest_by_name:
            errors.append(
                "public effect %s (=%d) in Harken.h has no manifest row" %
                (name, value))
    for name, value in manifest:
        if name not in public_by_name:
            errors.append(
                "manifest row %s has no matching public effect id in Harken.h" %
                name)
        elif public_by_name[name] != value:
            errors.append(
                "effect-type value mismatch for %s: manifest %d vs Harken.h %d" %
                (name, value, public_by_name[name]))

    # Row order must match ascending public value order (the registry rows are
    # indexed by effect type, and the pool/dispatch rely on that ordering).
    public_ascending = [name for name, _ in sorted(public, key=lambda p: p[1])]
    manifest_order = [name for name, _ in manifest]
    if not errors and manifest_order != public_ascending:
        errors.append(
            "manifest row order %r does not match ascending public effect "
            "order %r" % (manifest_order, public_ascending))

    if errors:
        for e in errors:
            print("ERROR: effect registry completeness: %s" % e,
                  file=sys.stderr)
        raise SystemExit(1)


