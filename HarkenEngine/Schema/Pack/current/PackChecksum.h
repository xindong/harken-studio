#define HARKEN_PACK_CHECKSUM_H

#include "PackFile.h"

#define HK_PACK_FNV1A64_OFFSET_BASIS UINT64_C(14695981039346656037)
#define HK_PACK_FNV1A64_PRIME UINT64_C(1099511628211)

static inline uint64_t hkPackFnv1a64(const void* data, size_t bytes, uint64_t hash) {
    const unsigned char* p = (const unsigned char*)data;
    for (size_t i = 0; i < bytes; ++i) {
        hash ^= (uint64_t)p[i];
        hash *= HK_PACK_FNV1A64_PRIME;
    }
    return hash;
}

static inline uint64_t hkPackFingerprintFinish(uint64_t hash) {
    return hash == 0 ? 1 : hash;
}

